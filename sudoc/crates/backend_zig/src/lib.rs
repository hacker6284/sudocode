#[derive(Default)]
struct TypeSet {
    types: BTreeMap<String, Ty>,
}

impl TypeSet {
    fn add(&mut self, ty: &Ty) {
        match ty {
            Ty::Int | Ty::Float | Ty::Bool | Ty::Infer(_) => {}
            Ty::Func { params, ret } => {
                for p in params {
                    self.add(p);
                }
                if let Some(r) = ret {
                    self.add(r);
                }
            }
            Ty::Map(k, v) => {
                self.add(k);
                self.add(v);
                self.types.insert(mangle(ty), ty.clone());
            }
            Ty::Set(e) => {
                self.add(e);
                self.types.insert(mangle(ty), ty.clone());
            }
            Ty::List(e) => {
                self.add(e);
                self.types.insert(mangle(ty), ty.clone());
            }
            Ty::Tuple(ts) => {
                for t in ts {
                    self.add(t);
                }
                if !ts.is_empty() {
                    self.types.insert(mangle(ty), ty.clone());
                }
            }
            Ty::Option_(e) => {
                self.add(e);
                self.types.insert(mangle(ty), ty.clone());
            }
            Ty::Result_(a, b) => {
                self.add(a);
                self.add(b);
                self.types.insert(mangle(ty), ty.clone());
            }
            Ty::Record(n) | Ty::Enum(n) => {
                self.types.insert(n.clone(), ty.clone());
            }
        }
    }
}

fn collect_types(m: &IrModule) -> TypeSet {
    let mut set = TypeSet::default();
    for r in &m.records {
        set.add(&Ty::Record(r.name.clone()));
        for f in &r.fields {
            let t = &f.ty;
            set.add(t);
        }
    }
    for e in &m.enums {
        set.add(&Ty::Enum(e.name.clone()));
        for v in &e.variants {
            for f in &v.fields {
            let t = &f.ty;
                set.add(t);
            }
        }
    }
    for c in &m.consts {
        set.add(&c.ty);
    }
    for f in &m.funcs {
        for p in &f.params {
            set.add(&p.ty);
        }
        if let Some(r) = &f.ret {
            set.add(r);
        }
        walk_stmts(&f.body, &mut set);
    }
    for t in &m.tests {
        walk_stmts(&t.body, &mut set);
    }
    set
}

fn collect_types_all(modules: &[IrModule]) -> TypeSet {
    let mut set = TypeSet::default();
    for m in modules {
        set.types.extend(collect_types(m).types);
    }
    set
}

