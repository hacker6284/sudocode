//! Zig backend: typed IR → readable Zig 0.16 sources + `sudo_rt.zig` runtime.
//!
//! One `.zig` file per sudo module (`dep.fn` → `dep.fn(...)` via `@import`),
//! plus a shared `sudo_rt.zig`. Traps are a closed Zig error set; functions
//! return `!T`, calls `try`, and `expect_trap` observes an error locally.
//! Value semantics: composite reads are deep-copied at owning store points.
//! Map/Set use a `StringHashMapUnmanaged` keyed by a canonical structural
//! encoding of the key. The entry module carries the TAP runner `main`.
//! See notes/friction-zig.md for the Zig 0.16 stdlib API reference.

use std::collections::{BTreeMap, BTreeSet, HashSet};

use sudoc_ir::never_written::{
    compute_address_taken, expr_root_var, func_is_address_taken,
};
use sudoc_ir::{
    BinaryOp, Builtin, IrExpr, IrExprKind, IrFunc, IrMatchArm, IrModule, IrPattern, IrStmt, Place,
    Ty, UnaryOp,
};
use sudoc_sdk::{Backend, GeneratedFile, TestRecipe};

mod reserved;

/// Shared Zig runtime, written alongside every generated module.
pub const RUNTIME: &str = include_str!("runtime/sudo_rt.zig");
pub const RUNTIME_FILE: &str = "sudo_rt.zig";

/// Emit a Zig module for the IR. When `with_tests` is set, `test` blocks
/// become `test_*` functions (the TAP `main` arrives in stage 3).
pub fn emit(module: &IrModule, with_tests: bool, is_entry: bool) -> String {
    let module = reserved::rename_reserved(module);
    emit_with(
        &module,
        std::slice::from_ref(&module),
        with_tests,
        is_entry,
        &BTreeSet::new(),
    )
}

/// Emit `module`, resolving cross-module callee signatures (inout-taking
/// functions in particular) against `all_modules` — the whole program,
/// not just `module` itself. `emit_program` calls this with the real
/// program; `emit` (single-module callers, back-compat) passes a
/// one-element slice and an empty `hoisted` set (fully self-contained file).
fn emit_with(
    module: &IrModule,
    all_modules: &[IrModule],
    with_tests: bool,
    is_entry: bool,
    hoisted: &BTreeSet<String>,
) -> String {
    let address_taken = compute_address_taken(all_modules);
    Emitter {
        m: module,
        all: all_modules,
        out: String::new(),
        indent: 0,
        tmp: 0,
        inouts: HashSet::new(),
        borrowed: HashSet::new(),
        address_taken,
        is_entry,
        trap_label: None,
        hoisted,
        in_func_body: false,
        scratch_used: false,
        ret_alloc_used: false,
        alloc_override: None,
        loop_depth: 0,
        loop_arena: None,
        loop_declared: HashSet::new(),
    }
    .run(with_tests)
}

struct Emitter<'a> {
    m: &'a IrModule,
    /// Every module in the program, for cross-module callee lookup.
    all: &'a [IrModule],
    out: String,
    indent: usize,
    tmp: usize,
    inouts: HashSet<String>,
    /// Read-only composite params of the function currently being emitted
    /// (`*const T` borrows). Fully reassigned at the top of each `emit_func`.
    borrowed: HashSet<String>,
    /// Whole-program set of function names (bare or `mod.fn`) that appear as
    /// `FuncRef` values — those functions keep by-value params (Guard 1).
    address_taken: HashSet<String>,
    is_entry: bool,
    /// Set while emitting an `expect_trap` body: fallible ops break to this
    /// labeled block instead of `try`/`return`-ing out of the test function.
    trap_label: Option<String>,
    /// Mangled type names declared in the shared `sudo_types.zig` file.
    /// Empty for single-module / `emit()` back-compat (everything local).
    hoisted: &'a BTreeSet<String>,
    /// True while emitting a sudo function body (not tests / consts / type ops).
    /// When set, `cur_alloc()` returns the per-call scratch arena.
    in_func_body: bool,
    /// Set when any allocation site in the current function body consulted
    /// `cur_alloc()`; drives whether the scratch-arena preamble is emitted.
    scratch_used: bool,
    /// Set when the body references `ret_alloc` as a copy destination (return /
    /// non-container inout). Avoids a pointless `_ = ret_alloc` discard.
    ret_alloc_used: bool,
    /// Override for `cur_alloc()` outside function bodies (per-test arena
    /// `ta.allocator()`, or const-init param `ca`). `None` falls back to the
    /// (now-unreachable) `rt.allocator()` string.
    alloc_override: Option<String>,
    /// Nesting depth of loops currently being emitted (outermost = 1).
    loop_depth: usize,
    /// Allocator expression for the outermost loop arena, e.g.
    /// `"_sudo_loop3.allocator()"`. Nested loops reuse it.
    loop_arena: Option<String>,
    /// Locals first-declared inside the current outermost loop (any depth).
    loop_declared: HashSet<String>,
}

impl Emitter<'_> {
    fn run(mut self, with_tests: bool) -> String {
        self.line(&format!(
            "// Generated by sudoc from {}.sudo — do not edit; edit the sudo source.",
            self.m.name
        ));
        // Only `rt` is imported; NaN/Inf literals go through `rt.nan()`/`rt.inf()`
        // so Zig does not flag an unused `std` import on pure-scalar modules.
        self.line("const rt = @import(\"sudo_rt.zig\");");
        for dep in &self.m.imports {
            self.line(&format!("const {dep} = @import(\"{dep}.zig\");"));
        }
        // Collect types before imports finish so we know whether this module
        // needs the shared monomorph file (`st`).
        let types = collect_types(self.m);
        if types.types.keys().any(|k| self.hoisted.contains(k)) {
            self.line("const st = @import(\"sudo_types.zig\");");
        }
        self.blank();

        // Stage-2 monomorphized types + copy/eq/canon helpers.
        self.emit_type_section(&types);

        // Scalars fold at emit time; composites are runtime-filled globals
        // (allocator-backed List/Map/Set cannot be comptime-initialized).
        for c in &self.m.consts {
            let ty = zig_ty(&c.ty);
            if matches!(c.ty, Ty::Int | Ty::Float | Ty::Bool) {
                let value = fold_const(&c.value, self.m);
                self.line(&format!("pub const {}: {ty} = {value};", c.name));
            } else {
                self.line(&format!("pub var {}: {ty} = undefined;", c.name));
            }
        }
        if !self.m.consts.is_empty() {
            self.blank();
        }
        // Always emit: every module can be called uniformly from main() and
        // from each import's transitive init (even modules with no composites
        // of their own may import a dep that has some).
        self.emit_const_init();

        for f in &self.m.funcs {
            self.emit_func(f);
            self.blank();
        }

        if with_tests {
            let names = sudoc_ir::names::test_fn_names(&self.m.tests);
            for (t, name) in self.m.tests.iter().zip(&names) {
                self.inouts.clear();
                self.borrowed.clear();
                self.line(&format!("pub fn {name}() rt.SudoError!void {{"));
                self.indent += 1;
                // Per-test arena: composite consts + top-level return values
                // land here and are freed by defer at test end.
                self.line("var _sudo_ta = rt.ArenaAllocator.init(rt.backing());");
                self.line("defer _sudo_ta.deinit();");
                let prev_override = self.alloc_override.take();
                self.alloc_override = Some("_sudo_ta.allocator()".to_string());
                // Rebuild composite constants (and transitively those of
                // imports) into this test's arena before the body runs.
                self.line("sudoResetConstsReady();");
                self.line("sudoInitConsts(_sudo_ta.allocator());");
                self.emit_stmts(&t.body);
                self.alloc_override = prev_override;
                self.indent -= 1;
                self.line("}");
                self.blank();
            }
            // The entry module carries the TAP runner `main`.
            if self.is_entry {
                self.line("pub fn main() void {");
                self.indent += 1;
                self.line("const _sudo_tests = [_]rt.TestCase{");
                self.indent += 1;
                for name in &names {
                    self.line(&format!(".{{ .name = \"{name}\", .func = &{name} }},"));
                }
                self.indent -= 1;
                self.line("};");
                self.line("rt.run_tests(&_sudo_tests);");
                self.indent -= 1;
                self.line("}");
            }
        }

        self.out
    }

    /// Idempotent module-constant initializer: transitively init imports, then
    /// build this module's composite constants via the same `store` path used
    /// by function bodies (deep-copies bare `Const` refs).
    ///
    /// Each test owns a per-test arena and rebuilds composite constants into
    /// it (`sudoResetConstsReady` then `sudoInitConsts(ta.allocator())`). The
    /// ready flag still makes a single init wave idempotent under diamond-
    /// shaped imports within one test.
    fn emit_const_init(&mut self) {
        self.line("var sudo_consts_ready: bool = false;");
        self.line("pub fn sudoResetConstsReady() void {");
        self.indent += 1;
        self.line("sudo_consts_ready = false;");
        for dep in &self.m.imports {
            self.line(&format!("{dep}.sudoResetConstsReady();"));
        }
        self.indent -= 1;
        self.line("}");
        self.blank();
        self.line("pub fn sudoInitConsts(_sudo_ca: rt.Allocator) void {");
        self.indent += 1;
        self.line("if (sudo_consts_ready) return;");
        self.line("sudo_consts_ready = true;");
        self.tmp = 0;
        self.inouts.clear();
        self.borrowed.clear();
        let prev_override = self.alloc_override.take();
        self.alloc_override = Some("_sudo_ca".to_string());
        // Zig 0.16 rejects unused params; modules with no imports and only
        // scalar (or no) consts never thread `ca` into a store / dep call.
        let mut ca_used = false;
        for dep in &self.m.imports {
            self.line(&format!("{dep}.sudoInitConsts(_sudo_ca);"));
            ca_used = true;
        }
        for c in &self.m.consts {
            if matches!(c.ty, Ty::Int | Ty::Float | Ty::Bool) {
                continue;
            }
            let code = self.store(&c.value);
            self.line(&format!("{} = {code};", c.name));
            ca_used = true;
        }
        if !ca_used {
            self.line("_ = _sudo_ca;");
        }
        self.alloc_override = prev_override;
        self.indent -= 1;
        self.line("}");
        self.blank();
    }

    fn emit_type_section(&mut self, types: &TypeSet) {
        if types.types.is_empty() && self.m.records.is_empty() && self.m.enums.is_empty() {
            return;
        }

        // Named record/enum type decls first (enums may self-reference via pointers).
        for r in &self.m.records {
            self.line(&format!("pub const {} = struct {{", r.name));
            self.indent += 1;
            for f in &r.fields {
            let fname = &f.name;
            let fty = &f.ty;
                self.line(&format!("{fname}: {},", zig_ty(fty)));
            }
            self.indent -= 1;
            self.line("};");
            self.blank();
        }
        for e in &self.m.enums {
            self.line(&format!("pub const {} = union(enum) {{", e.name));
            self.indent += 1;
            for v in &e.variants {
                if v.fields.is_empty() {
                    self.line(&format!("{}: void,", v.name));
                } else if v.fields.len() == 1 {
                    let fname = &v.fields[0].name;
                    let fty = &v.fields[0].ty;
                    let pty = payload_ty(fty);
                    self.line(&format!("{}: {}, // field `{fname}`", v.name, pty));
                } else {
                    self.line(&format!("{}: struct {{", v.name));
                    self.indent += 1;
                    for f in &v.fields {
            let fname = &f.name;
            let fty = &f.ty;
                        self.line(&format!("{fname}: {},", payload_ty(fty)));
                    }
                    self.indent -= 1;
                    self.line("},");
                }
            }
            self.indent -= 1;
            self.line("};");
            self.blank();
        }

        // Non-hoisted monomorphs (and all records/enums) stay fully local.
        let local = TypeSet {
            types: types
                .types
                .iter()
                .filter(|(k, _)| !self.hoisted.contains(*k))
                .map(|(k, v)| (k.clone(), v.clone()))
                .collect(),
        };

        // Monomorphized aliases (List/Tuple/Option/Result) in topo order.
        let order = topo_order(&local, self.m);
        for name in &order {
            let ty = &local.types[name];
            match ty {
                Ty::List(elem) => {
                    self.line(&format!(
                        "pub const {name} = rt.SudoList({});",
                        zig_ty(elem)
                    ));
                }
                Ty::Tuple(ts) => {
                    self.line(&format!("pub const {name} = struct {{"));
                    self.indent += 1;
                    for (i, t) in ts.iter().enumerate() {
                        self.line(&format!("f{i}: {},", zig_ty(t)));
                    }
                    self.indent -= 1;
                    self.line("};");
                }
                Ty::Option_(inner) => {
                    let inner_z = if boxed_in_payload(inner) {
                        format!("*const {}", zig_ty(inner))
                    } else {
                        zig_ty(inner)
                    };
                    self.line(&format!("pub const {name} = ?{inner_z};"));
                }
                Ty::Result_(ok, err) => {
                    let ok_z = if boxed_in_payload(ok) {
                        format!("*const {}", zig_ty(ok))
                    } else {
                        zig_ty(ok)
                    };
                    let err_z = if boxed_in_payload(err) {
                        format!("*const {}", zig_ty(err))
                    } else {
                        zig_ty(err)
                    };
                    self.line(&format!(
                        "pub const {name} = union(enum) {{ Ok: {ok_z}, Err: {err_z} }};"
                    ));
                }
                Ty::Map(k, v) => {
                    self.line(&format!(
                        "pub const {name} = rt.SudoMap({}, {}, {});",
                        zig_ty(k),
                        zig_ty(v),
                        keyapp_fn(k)
                    ));
                }
                Ty::Set(e) => {
                    self.line(&format!(
                        "pub const {name} = rt.SudoSet({}, {});",
                        zig_ty(e),
                        keyapp_fn(e)
                    ));
                }
                // Record/Enum already emitted above by declaration order.
                Ty::Record(_) | Ty::Enum(_) => {}
                _ => {}
            }
        }
        if !order.is_empty() {
            self.blank();
        }

        // Portable monomorphs live in `sudo_types.zig`; alias so bare mangled
        // names resolve to the single shared nominal type.
        let mut emitted_hoist = false;
        for name in types.types.keys() {
            if !self.hoisted.contains(name) {
                continue;
            }
            self.line(&format!("pub const {name} = st.{name};"));
            self.line(&format!("pub const copy_{name} = st.copy_{name};"));
            self.line(&format!("pub const eq_{name} = st.eq_{name};"));
            self.line(&format!("pub const canon_{name} = st.canon_{name};"));
            emitted_hoist = true;
        }
        if emitted_hoist {
            self.blank();
        }

        // Structural-key encoders for every composite type used as a Map/Set key.
        // Use the full type set so a local non-portable Map/Set can still pull
        // in a portable (hoisted) key type.
        let key_types = collect_key_types(types, self.m);
        let mut emitted_keyapp = false;
        for name in &key_types {
            if self.hoisted.contains(name) {
                self.line(&format!("pub const keyapp_{name} = st.keyapp_{name};"));
                emitted_keyapp = true;
            } else if let Some(ty) = types.types.get(name) {
                let ty = ty.clone();
                self.emit_keyapp(name, &ty);
                emitted_keyapp = true;
            }
        }
        if emitted_keyapp {
            self.blank();
        }

        // copy / eq / canon for every composite monomorph declared locally.
        for name in &order {
            let ty = &local.types[name];
            if !matches!(
                ty,
                Ty::List(_)
                    | Ty::Tuple(_)
                    | Ty::Option_(_)
                    | Ty::Result_(..)
                    | Ty::Record(_)
                    | Ty::Enum(_)
                    | Ty::Map(..)
                    | Ty::Set(_)
            ) {
                continue;
            }
            self.emit_type_ops(name, ty);
        }
    }

    /// Whether `copy_{ty}`'s body references its `alloc` param — i.e. it builds
    /// a container literal, boxes a payload, or recurses into a `copy_*`. Mirrors
    /// the branches in `emit_type_ops`'s copy section exactly.
    fn copy_uses_alloc(&self, ty: &Ty) -> bool {
        match ty {
            Ty::List(_) | Ty::Map(..) | Ty::Set(_) => true,
            Ty::Tuple(ts) => ts.iter().any(needs_dup),
            Ty::Record(rname) => self
                .m
                .record(rname)
                .expect("record")
                .fields
                .iter()
                .any(|f| needs_dup(&f.ty)),
            Ty::Enum(ename) => self
                .m
                .enum_(ename)
                .expect("enum")
                .variants
                .iter()
                .any(|v| {
                    v.fields
                        .iter()
                        .any(|f| needs_dup(&f.ty) || boxed_in_payload(&f.ty))
                }),
            Ty::Option_(t) => needs_dup(t) || boxed_in_payload(t),
            Ty::Result_(a, b) => {
                needs_dup(a) || boxed_in_payload(a) || needs_dup(b) || boxed_in_payload(b)
            }
            _ => false,
        }
    }

    fn emit_type_ops(&mut self, name: &str, ty: &Ty) {
        // ── copy ──
        self.line(&format!(
            "pub fn copy_{name}(alloc: rt.Allocator, v: {name}) {name} {{"
        ));
        self.indent += 1;
        // The `alloc` param threads the allocator through recursive copies and
        // container/box construction; a copy body over purely-scalar shape never
        // touches it, so discard to satisfy Zig's unused-parameter check.
        if !self.copy_uses_alloc(ty) {
            self.line("_ = alloc;");
        }
        match ty {
            Ty::List(elem) => {
                self.line(&format!("var out: {name} = .{{ .alloc = alloc }};"));
                self.line("_ = &out;");
                self.line("for (v.items()) |x| {");
                self.indent += 1;
                let elem_copy = if needs_dup(elem) {
                    format!("copy_{}(alloc, x)", mangle(elem))
                } else {
                    "x".into()
                };
                self.line(&format!("out.append({elem_copy}) catch @panic(\"sudo: arena OOM\");"));
                self.indent -= 1;
                self.line("}");
                self.line("return out;");
            }
            Ty::Tuple(ts) => {
                let mut fields = Vec::new();
                for (i, t) in ts.iter().enumerate() {
                    let src = format!("v.f{i}");
                    fields.push(if needs_dup(t) {
                        format!(".f{i} = copy_{}(alloc, {src})", mangle(t))
                    } else {
                        format!(".f{i} = {src}")
                    });
                }
                self.line(&format!("return .{{ {} }};", fields.join(", ")));
            }
            Ty::Record(rname) => {
                let r = self.m.record(rname).expect("record");
                let mut fields = Vec::new();
                for f in &r.fields {
            let fname = &f.name;
            let fty = &f.ty;
                    let src = format!("v.{fname}");
                    fields.push(if needs_dup(fty) {
                        format!(".{fname} = copy_{}(alloc, {src})", mangle(fty))
                    } else {
                        format!(".{fname} = {src}")
                    });
                }
                self.line(&format!("return .{{ {} }};", fields.join(", ")));
            }
            Ty::Enum(ename) => {
                let e = self.m.enum_(ename).expect("enum");
                self.line("return switch (v) {");
                self.indent += 1;
                for v in &e.variants {
                    if v.fields.is_empty() {
                        self.line(&format!(".{vn} => .{{ .{vn} = {{}} }},", vn = v.name));
                    } else if v.fields.len() == 1 {
                        let fname = &v.fields[0].name;
                    let fty = &v.fields[0].ty;
                        let _ = fname;
                        let payload = if boxed_in_payload(fty) {
                            let inner = if needs_dup(fty) {
                                format!("copy_{}(alloc, p.*)", mangle(fty))
                            } else {
                                "p.*".into()
                            };
                            format!("rt.box(alloc, {}, {inner})", zig_ty(fty))
                        } else if needs_dup(fty) {
                            format!("copy_{}(alloc, p)", mangle(fty))
                        } else {
                            "p".into()
                        };
                        self.line(&format!(
                            ".{vn} => |p| .{{ .{vn} = {payload} }},",
                            vn = v.name
                        ));
                    } else {
                        self.line(&format!(".{vn} => |p| .{{ .{vn} = .{{", vn = v.name));
                        self.indent += 1;
                        for f in &v.fields {
            let fname = &f.name;
            let fty = &f.ty;
                            let field = if boxed_in_payload(fty) {
                                let inner = if needs_dup(fty) {
                                    format!("copy_{}(alloc, p.{fname}.*)", mangle(fty))
                                } else {
                                    format!("p.{fname}.*")
                                };
                                format!(
                                    ".{fname} = rt.box(alloc, {}, {inner}),",
                                    zig_ty(fty)
                                )
                            } else if needs_dup(fty) {
                                format!(".{fname} = copy_{}(alloc, p.{fname}),", mangle(fty))
                            } else {
                                format!(".{fname} = p.{fname},")
                            };
                            self.line(&field);
                        }
                        self.indent -= 1;
                        self.line("} },");
                    }
                }
                self.indent -= 1;
                self.line("};");
            }
            Ty::Option_(inner) => {
                if boxed_in_payload(inner) {
                    let copy_inner = if needs_dup(inner) {
                        format!("copy_{}(alloc, p.*)", mangle(inner))
                    } else {
                        "p.*".into()
                    };
                    self.line(&format!(
                        "return if (v) |p| rt.box(alloc, {}, {copy_inner}) else null;",
                        zig_ty(inner)
                    ));
                } else if needs_dup(inner) {
                    self.line(&format!(
                        "return if (v) |x| copy_{}(alloc, x) else null;",
                        mangle(inner)
                    ));
                } else {
                    self.line("return v;");
                }
            }
            Ty::Result_(ok, err) => {
                self.line("return switch (v) {");
                self.indent += 1;
                // Ok
                if boxed_in_payload(ok) {
                    let c = if needs_dup(ok) {
                        format!("copy_{}(alloc, p.*)", mangle(ok))
                    } else {
                        "p.*".into()
                    };
                    self.line(&format!(
                        ".Ok => |p| .{{ .Ok = rt.box(alloc, {}, {c}) }},",
                        zig_ty(ok)
                    ));
                } else if needs_dup(ok) {
                    self.line(&format!(".Ok => |x| .{{ .Ok = copy_{}(alloc, x) }},", mangle(ok)));
                } else {
                    self.line(".Ok => |x| .{ .Ok = x },");
                }
                // Err
                if boxed_in_payload(err) {
                    let c = if needs_dup(err) {
                        format!("copy_{}(alloc, p.*)", mangle(err))
                    } else {
                        "p.*".into()
                    };
                    self.line(&format!(
                        ".Err => |p| .{{ .Err = rt.box(alloc, {}, {c}) }},",
                        zig_ty(err)
                    ));
                } else if needs_dup(err) {
                    self.line(&format!(".Err => |x| .{{ .Err = copy_{}(alloc, x) }},", mangle(err)));
                } else {
                    self.line(".Err => |x| .{ .Err = x },");
                }
                self.indent -= 1;
                self.line("};");
            }
            Ty::Map(k, v) => {
                self.line("var vv = v;");
                self.line("_ = &vv;");
                self.line(&format!("var out: {name} = .{{ .alloc = alloc }};"));
                self.line("_ = &out;");
                self.line("var it = vv.map.valueIterator();");
                self.line("while (it.next()) |kv| {");
                self.indent += 1;
                self.line(&format!(
                    "out.put({}, {});",
                    copy_expr(k, "kv.k", "alloc"),
                    copy_expr(v, "kv.v", "alloc")
                ));
                self.indent -= 1;
                self.line("}");
                self.line("return out;");
            }
            Ty::Set(elem) => {
                self.line("var vv = v;");
                self.line("_ = &vv;");
                self.line(&format!("var out: {name} = .{{ .alloc = alloc }};"));
                self.line("_ = &out;");
                self.line("var it = vv.map.valueIterator();");
                self.line("while (it.next()) |ep| {");
                self.indent += 1;
                self.line(&format!("_ = out.add({});", copy_expr(elem, "ep.*", "alloc")));
                self.indent -= 1;
                self.line("}");
                self.line("return out;");
            }
            _ => self.line("return v;"),
        }
        self.indent -= 1;
        self.line("}");
        self.blank();

        // ── eq ──
        self.line(&format!("pub fn eq_{name}(a: {name}, b: {name}) bool {{"));
        self.indent += 1;
        match ty {
            Ty::List(elem) => {
                self.line("if (a.len() != b.len()) return false;");
                self.line("for (a.items(), b.items()) |x, y| {");
                self.indent += 1;
                let cmp = eq_expr(elem, "x", "y");
                self.line(&format!("if (!({cmp})) return false;"));
                self.indent -= 1;
                self.line("}");
                self.line("return true;");
            }
            Ty::Tuple(ts) => {
                for (i, t) in ts.iter().enumerate() {
                    let cmp = eq_expr(t, &format!("a.f{i}"), &format!("b.f{i}"));
                    self.line(&format!("if (!({cmp})) return false;"));
                }
                self.line("return true;");
            }
            Ty::Record(rname) => {
                let r = self.m.record(rname).expect("record");
                for f in &r.fields {
            let fname = &f.name;
            let fty = &f.ty;
                    let cmp = eq_expr(fty, &format!("a.{fname}"), &format!("b.{fname}"));
                    self.line(&format!("if (!({cmp})) return false;"));
                }
                self.line("return true;");
            }
            Ty::Enum(ename) => {
                let e = self.m.enum_(ename).expect("enum");
                self.line("return switch (a) {");
                self.indent += 1;
                for v in &e.variants {
                    if v.fields.is_empty() {
                        self.line(&format!(
                            ".{vn} => switch (b) {{ .{vn} => true, else => false }},",
                            vn = v.name
                        ));
                    } else if v.fields.len() == 1 {
                        let fty = &v.fields[0].ty;
                        self.line(&format!(".{vn} => |pa| switch (b) {{", vn = v.name));
                        self.indent += 1;
                        if boxed_in_payload(fty) {
                            let cmp = eq_expr(fty, "pa.*", "pb.*");
                            self.line(&format!(".{vn} => |pb| {cmp},", vn = v.name));
                        } else {
                            let cmp = eq_expr(fty, "pa", "pb");
                            self.line(&format!(".{vn} => |pb| {cmp},", vn = v.name));
                        }
                        self.line("else => false,");
                        self.indent -= 1;
                        self.line("},");
                    } else {
                        self.line(&format!(".{vn} => |pa| switch (b) {{", vn = v.name));
                        self.indent += 1;
                        self.line(&format!(".{vn} => |pb| {{", vn = v.name));
                        self.indent += 1;
                        for f in &v.fields {
            let fname = &f.name;
            let fty = &f.ty;
                            let (la, lb) = if boxed_in_payload(fty) {
                                (format!("pa.{fname}.*"), format!("pb.{fname}.*"))
                            } else {
                                (format!("pa.{fname}"), format!("pb.{fname}"))
                            };
                            let cmp = eq_expr(fty, &la, &lb);
                            self.line(&format!("if (!({cmp})) return false;"));
                        }
                        self.line("return true;");
                        self.indent -= 1;
                        self.line("},");
                        self.line("else => false,");
                        self.indent -= 1;
                        self.line("},");
                    }
                }
                self.indent -= 1;
                self.line("};");
            }
            Ty::Option_(inner) => {
                self.line("if (a) |xa| {");
                self.indent += 1;
                self.line("if (b) |xb| {");
                self.indent += 1;
                if boxed_in_payload(inner) {
                    let cmp = eq_expr(inner, "xa.*", "xb.*");
                    self.line(&format!("return {cmp};"));
                } else {
                    let cmp = eq_expr(inner, "xa", "xb");
                    self.line(&format!("return {cmp};"));
                }
                self.indent -= 1;
                self.line("} else return false;");
                self.indent -= 1;
                self.line("} else return b == null;");
            }
            Ty::Result_(ok, err) => {
                self.line("return switch (a) {");
                self.indent += 1;
                self.line(".Ok => |xa| switch (b) {");
                self.indent += 1;
                if boxed_in_payload(ok) {
                    let cmp = eq_expr(ok, "xa.*", "xb.*");
                    self.line(&format!(".Ok => |xb| {cmp},"));
                } else {
                    let cmp = eq_expr(ok, "xa", "xb");
                    self.line(&format!(".Ok => |xb| {cmp},"));
                }
                self.line("else => false,");
                self.indent -= 1;
                self.line("},");
                self.line(".Err => |xa| switch (b) {");
                self.indent += 1;
                if boxed_in_payload(err) {
                    let cmp = eq_expr(err, "xa.*", "xb.*");
                    self.line(&format!(".Err => |xb| {cmp},"));
                } else {
                    let cmp = eq_expr(err, "xa", "xb");
                    self.line(&format!(".Err => |xb| {cmp},"));
                }
                self.line("else => false,");
                self.indent -= 1;
                self.line("},");
                self.indent -= 1;
                self.line("};");
            }
            Ty::Map(_, v) => {
                self.line("if (a.size() != b.size()) return false;");
                self.line("var aa = a;");
                self.line("_ = &aa;");
                self.line("var it = aa.map.valueIterator();");
                self.line("while (it.next()) |kv| {");
                self.indent += 1;
                self.line("if (b.getPtr(kv.k)) |bp| {");
                self.indent += 1;
                let cmp = eq_expr(v, "kv.v", "bp.*");
                self.line(&format!("if (!({cmp})) return false;"));
                self.indent -= 1;
                self.line("} else return false;");
                self.indent -= 1;
                self.line("}");
                self.line("return true;");
            }
            Ty::Set(_) => {
                self.line("if (a.size() != b.size()) return false;");
                self.line("var aa = a;");
                self.line("_ = &aa;");
                self.line("var it = aa.map.valueIterator();");
                self.line("while (it.next()) |ep| {");
                self.indent += 1;
                self.line("if (!b.has(ep.*)) return false;");
                self.indent -= 1;
                self.line("}");
                self.line("return true;");
            }
            _ => self.line("return false;"),
        }
        self.indent -= 1;
        self.line("}");
        self.blank();

        // ── canon ──
        self.line(&format!("pub fn canon_{name}(v: {name}) void {{"));
        self.indent += 1;
        match ty {
            Ty::List(elem) => {
                self.line("rt.det_str(\"[\");");
                self.line("for (v.items(), 0..) |x, i| {");
                self.indent += 1;
                self.line("if (i > 0) rt.det_str(\", \");");
                self.emit_canon_value(elem, "x");
                self.indent -= 1;
                self.line("}");
                self.line("rt.det_str(\"]\");");
            }
            Ty::Tuple(ts) => {
                self.line("rt.det_str(\"[\");");
                for (i, t) in ts.iter().enumerate() {
                    if i > 0 {
                        self.line("rt.det_str(\", \");");
                    }
                    self.emit_canon_value(t, &format!("v.f{i}"));
                }
                self.line("rt.det_str(\"]\");");
            }
            Ty::Record(rname) => {
                let r = self.m.record(rname).expect("record");
                self.line(&format!("rt.det_str(\"{{\\\"r\\\": \\\"{rname}\\\", \\\"v\\\": [\");"));
                for (i, f) in r.fields.iter().enumerate() {
                    if i > 0 {
                        self.line("rt.det_str(\", \");");
                    }
                    self.emit_canon_value(&f.ty, &format!("v.{}", f.name));
                }
                self.line("rt.det_str(\"]}\");");
            }
            Ty::Enum(ename) => {
                let e = self.m.enum_(ename).expect("enum");
                self.line("switch (v) {");
                self.indent += 1;
                for v in &e.variants {
                    if v.fields.is_empty() {
                        self.line(&format!(
                            ".{vn} => rt.det_str(\"{{\\\"e\\\": \\\"{ename}.{vn}\\\"}}\"),",
                            vn = v.name
                        ));
                    } else if v.fields.len() == 1 {
                        let fty = &v.fields[0].ty;
                        self.line(&format!(".{vn} => |p| {{", vn = v.name));
                        self.indent += 1;
                        self.line(&format!(
                            "rt.det_str(\"{{\\\"e\\\": \\\"{ename}.{vn}\\\", \\\"v\\\": [\");",
                            vn = v.name
                        ));
                        if boxed_in_payload(fty) {
                            self.emit_canon_value(fty, "p.*");
                        } else {
                            self.emit_canon_value(fty, "p");
                        }
                        self.line("rt.det_str(\"]}\");");
                        self.indent -= 1;
                        self.line("},");
                    } else {
                        self.line(&format!(".{vn} => |p| {{", vn = v.name));
                        self.indent += 1;
                        self.line(&format!(
                            "rt.det_str(\"{{\\\"e\\\": \\\"{ename}.{vn}\\\", \\\"v\\\": [\");",
                            vn = v.name
                        ));
                        for (i, f) in v.fields.iter().enumerate() {
                            if i > 0 {
                                self.line("rt.det_str(\", \");");
                            }
                            if boxed_in_payload(&f.ty) {
                                self.emit_canon_value(&f.ty, &format!("p.{}.*", f.name));
                            } else {
                                self.emit_canon_value(&f.ty, &format!("p.{}", f.name));
                            }
                        }
                        self.line("rt.det_str(\"]}\");");
                        self.indent -= 1;
                        self.line("},");
                    }
                }
                self.indent -= 1;
                self.line("}");
            }
            Ty::Option_(inner) => {
                self.line("if (v) |x| {");
                self.indent += 1;
                self.line("rt.det_str(\"{\\\"e\\\": \\\"Option.Some\\\", \\\"v\\\": [\");");
                if boxed_in_payload(inner) {
                    self.emit_canon_value(inner, "x.*");
                } else {
                    self.emit_canon_value(inner, "x");
                }
                self.line("rt.det_str(\"]}\");");
                self.indent -= 1;
                self.line("} else {");
                self.indent += 1;
                self.line("rt.det_str(\"{\\\"e\\\": \\\"Option.None\\\"}\");");
                self.indent -= 1;
                self.line("}");
            }
            Ty::Result_(ok, err) => {
                self.line("switch (v) {");
                self.indent += 1;
                self.line(".Ok => |x| {");
                self.indent += 1;
                self.line("rt.det_str(\"{\\\"e\\\": \\\"Result.Ok\\\", \\\"v\\\": [\");");
                if boxed_in_payload(ok) {
                    self.emit_canon_value(ok, "x.*");
                } else {
                    self.emit_canon_value(ok, "x");
                }
                self.line("rt.det_str(\"]}\");");
                self.indent -= 1;
                self.line("},");
                self.line(".Err => |x| {");
                self.indent += 1;
                self.line("rt.det_str(\"{\\\"e\\\": \\\"Result.Err\\\", \\\"v\\\": [\");");
                if boxed_in_payload(err) {
                    self.emit_canon_value(err, "x.*");
                } else {
                    self.emit_canon_value(err, "x");
                }
                self.line("rt.det_str(\"]}\");");
                self.indent -= 1;
                self.line("},");
                self.indent -= 1;
                self.line("}");
            }
            Ty::Map(k, v) => {
                self.line("var vv = v;");
                self.line("_ = &vv;");
                self.line("rt.det_str(\"{\\\"map\\\": [\");");
                self.line("var it = vv.map.valueIterator();");
                self.line("var i: usize = 0;");
                self.line("while (it.next()) |kv| : (i += 1) {");
                self.indent += 1;
                self.line("if (i > 0) rt.det_str(\", \");");
                self.line("rt.det_str(\"[\");");
                self.emit_canon_value(k, "kv.k");
                self.line("rt.det_str(\", \");");
                self.emit_canon_value(v, "kv.v");
                self.line("rt.det_str(\"]\");");
                self.indent -= 1;
                self.line("}");
                self.line("rt.det_str(\"]}\");");
            }
            Ty::Set(elem) => {
                self.line("var vv = v;");
                self.line("_ = &vv;");
                self.line("rt.det_str(\"{\\\"set\\\": [\");");
                self.line("var it = vv.map.valueIterator();");
                self.line("var i: usize = 0;");
                self.line("while (it.next()) |ep| : (i += 1) {");
                self.indent += 1;
                self.line("if (i > 0) rt.det_str(\", \");");
                self.emit_canon_value(elem, "ep.*");
                self.indent -= 1;
                self.line("}");
                self.line("rt.det_str(\"]}\");");
            }
            _ => {}
        }
        self.indent -= 1;
        self.line("}");
        self.blank();
    }

    /// Append the structural encoding of a composite key type to the scratch
    /// key buffer (`keyapp_<mangle>`). Scalars route to `rt.key_i64/key_bool`.
    fn emit_keyapp(&mut self, name: &str, ty: &Ty) {
        self.line(&format!("pub fn keyapp_{name}(v: {name}) void {{"));
        self.indent += 1;
        match ty {
            Ty::List(elem) => {
                self.line("rt.key_bytes(\"L[\");");
                self.line("for (v.items()) |x| {");
                self.indent += 1;
                self.emit_keyapp_value(elem, "x");
                self.indent -= 1;
                self.line("}");
                self.line("rt.key_bytes(\"]\");");
            }
            Ty::Tuple(ts) => {
                self.line("rt.key_bytes(\"(\");");
                for (i, t) in ts.iter().enumerate() {
                    self.emit_keyapp_value(t, &format!("v.f{i}"));
                }
                self.line("rt.key_bytes(\")\");");
            }
            Ty::Record(rname) => {
                let r = self.m.record(rname).expect("record");
                self.line(&format!("rt.key_bytes(\"R{{{rname}:\");"));
                for f in &r.fields {
            let fname = &f.name;
            let fty = &f.ty;
                    self.emit_keyapp_value(fty, &format!("v.{fname}"));
                }
                self.line("rt.key_bytes(\"}\");");
            }
            Ty::Enum(ename) => {
                let e = self.m.enum_(ename).expect("enum");
                self.line("switch (v) {");
                self.indent += 1;
                for var in &e.variants {
                    if var.fields.is_empty() {
                        self.line(&format!(
                            ".{vn} => rt.key_bytes(\"E{vn};\"),",
                            vn = var.name
                        ));
                    } else if var.fields.len() == 1 {
                        let fty = &var.fields[0].ty;
                        self.line(&format!(".{vn} => |p| {{", vn = var.name));
                        self.indent += 1;
                        self.line(&format!("rt.key_bytes(\"E{vn}(\");", vn = var.name));
                        let acc = if boxed_in_payload(fty) { "p.*" } else { "p" };
                        self.emit_keyapp_value(fty, acc);
                        self.line("rt.key_bytes(\")\");");
                        self.indent -= 1;
                        self.line("},");
                    } else {
                        self.line(&format!(".{vn} => |p| {{", vn = var.name));
                        self.indent += 1;
                        self.line(&format!("rt.key_bytes(\"E{vn}(\");", vn = var.name));
                        for f in &var.fields {
            let fname = &f.name;
            let fty = &f.ty;
                            let acc = if boxed_in_payload(fty) {
                                format!("p.{fname}.*")
                            } else {
                                format!("p.{fname}")
                            };
                            self.emit_keyapp_value(fty, &acc);
                        }
                        self.line("rt.key_bytes(\")\");");
                        self.indent -= 1;
                        self.line("},");
                    }
                }
                self.indent -= 1;
                self.line("}");
            }
            Ty::Option_(inner) => {
                self.line("if (v) |p| {");
                self.indent += 1;
                self.line("rt.key_bytes(\"S(\");");
                let acc = if boxed_in_payload(inner) { "p.*" } else { "p" };
                self.emit_keyapp_value(inner, acc);
                self.line("rt.key_bytes(\")\");");
                self.indent -= 1;
                self.line("} else rt.key_bytes(\"N;\");");
            }
            Ty::Result_(ok, err) => {
                self.line("switch (v) {");
                self.indent += 1;
                let ok_acc = if boxed_in_payload(ok) { "p.*" } else { "p" };
                self.line(".Ok => |p| {");
                self.indent += 1;
                self.line("rt.key_bytes(\"K(\");");
                self.emit_keyapp_value(ok, ok_acc);
                self.line("rt.key_bytes(\")\");");
                self.indent -= 1;
                self.line("},");
                let err_acc = if boxed_in_payload(err) { "p.*" } else { "p" };
                self.line(".Err => |p| {");
                self.indent += 1;
                self.line("rt.key_bytes(\"X(\");");
                self.emit_keyapp_value(err, err_acc);
                self.line("rt.key_bytes(\")\");");
                self.indent -= 1;
                self.line("},");
                self.indent -= 1;
                self.line("}");
            }
            _ => {}
        }
        self.indent -= 1;
        self.line("}");
        self.blank();
    }

    fn emit_keyapp_value(&mut self, ty: &Ty, expr: &str) {
        match ty {
            Ty::Int => self.line(&format!("rt.key_i64({expr});")),
            Ty::Bool => self.line(&format!("rt.key_bool({expr});")),
            Ty::Float => unreachable_shape("float in map/set key"),
            _ => self.line(&format!("keyapp_{}({expr});", mangle(ty))),
        }
    }

    fn emit_canon_value(&mut self, ty: &Ty, expr: &str) {
        match ty {
            Ty::Int => self.line(&format!("rt.det_i64({expr});")),
            Ty::Float => self.line(&format!("rt.det_f64({expr});")),
            Ty::Bool => self.line(&format!("rt.det_bool({expr});")),
            Ty::Func { .. } => self.line("rt.det_str(\"<func>\");"),
            _ => self.line(&format!("canon_{}({expr});", mangle(ty))),
        }
    }

    fn emit_func(&mut self, f: &IrFunc) {
        self.inouts = f
            .params
            .iter()
            .filter(|p| p.inout)
            .map(|p| p.name.clone())
            .collect();

        // Params that the body writes to (rebind / field / index / inout arg /
        // mutating method) need a mutable local, since Zig params are const.
        let written: HashSet<String> = f
            .params
            .iter()
            .filter(|p| !p.inout && !p.never_written)
            .map(|p| p.name.clone())
            .collect();
        self.borrowed = func_borrow_eligible(f, self.m, &self.address_taken);

        // Uniform first param for every sudo function (fn-pointer uniformity).
        // Unused until a later stage; silence Zig 0.16 unused-param errors.
        // `rt.Allocator` (= std.mem.Allocator); modules only import `rt`, not `std`.
        let mut params = vec!["_sudo_ret_alloc: rt.Allocator".to_string()];
        let mut shadows = Vec::new();
        for p in &f.params {
            let ty = zig_ty(&p.ty);
            if p.inout {
                params.push(format!("{}: *{ty}", p.name));
            } else if self.borrowed.contains(&p.name) {
                params.push(format!("{}: *const {ty}", p.name));
            } else if written.contains(&p.name) {
                params.push(format!("{}_arg: {ty}", p.name));
                shadows.push(p.name.clone());
            } else {
                params.push(format!("{}: {ty}", p.name));
            }
        }
        let ret = match &f.ret {
            Some(t) => format!("rt.SudoError!{}", zig_ty(t)),
            None => "rt.SudoError!void".into(),
        };
        self.line(&format!(
            "pub fn {}({}) {ret} {{",
            f.name,
            params.join(", ")
        ));
        self.indent += 1;
        // Buffer body first; preamble (scratch arena or `_ = ret_alloc`) is
        // inserted at the body start based on whether anything allocated.
        let insert_at = self.out.len();
        self.in_func_body = true;
        self.scratch_used = false;
        self.ret_alloc_used = false;
        // Rebind written params to owned, mutable locals (call-site `store`
        // already deep-copied managed args, so this shallow rebind is enough).
        for n in &shadows {
            self.line(&format!("var {n} = {n}_arg;"));
            self.line(&format!("_ = &{n};"));
        }
        self.emit_stmts(&f.body);
        self.in_func_body = false;
        let pad = "    ".repeat(self.indent);
        // Scratch draws from a real freeing allocator (`rt.backing()`), not
        // `ret_alloc` — so arena deinit truly reclaims per call. The two
        // decisions are independent: scratch may need the arena even when
        // nothing copies into `ret_alloc`, and `ret_alloc` still needs a
        // discard when unused (Zig 0.16 rejects unused params).
        let mut preamble = String::new();
        if self.scratch_used {
            preamble.push_str(&format!(
                "{pad}var _sudo_scratch = rt.ArenaAllocator.init(rt.backing());\n\
                 {pad}defer _sudo_scratch.deinit();\n"
            ));
        }
        if !self.ret_alloc_used {
            preamble.push_str(&format!("{pad}_ = _sudo_ret_alloc;\n"));
        }
        // Zig 0.16 rejects unused function parameters. User params the body
        // never references need an explicit discard. Written params are already
        // covered by their shadow rebind (`_ = &{name}`), so skip those. (F6)
        for p in &f.params {
            if shadows.contains(&p.name) {
                continue;
            }
            if !binder_used(&f.body, &p.name) {
                preamble.push_str(&format!("{pad}_ = {};\n", p.name));
            }
        }
        self.out.insert_str(insert_at, &preamble);
        self.indent -= 1;
        self.line("}");
    }

    fn emit_stmts(&mut self, stmts: &[IrStmt]) {
        for s in stmts {
            self.emit_stmt(s);
        }
    }

    fn emit_stmt(&mut self, s: &IrStmt) {
        match s {
            IrStmt::Assign {
                target,
                value,
                declares,
            } => {
                // Index assign → list.put
                if let Place::Index {
                    base,
                    base_ty,
                    index,
                } = target
                {
                    match base_ty {
                        Ty::List(_) => {
                            let base_lv = self.place_lvalue(base);
                            let idx = self.expr(index);
                            let esc = self.place_escapes(base);
                            let val =
                                self.store_to(value, &format!("{base_lv}.alloc"), esc);
                            self.try_line(&format!("{base_lv}.put({idx}, {val})"));
                        }
                        Ty::Map(..) => {
                            // Insert-or-overwrite. Key is only read transiently
                            // (SudoMap.put re-encodes + dupes into self.alloc);
                            // value is stored into the map's carried allocator.
                            let base_lv = self.place_lvalue(base);
                            let esc = self.place_escapes(base);
                            // The map RETAINS the key value (KV{k,v}), not just
                            // its encoding, so the key must outlive the loop
                            // arena too — copy it into the map's own allocator.
                            let key =
                                self.store_to(index, &format!("{base_lv}.alloc"), esc);
                            let val =
                                self.store_to(value, &format!("{base_lv}.alloc"), esc);
                            self.line(&format!("{base_lv}.put({key}, {val});"));
                        }
                        _ => unreachable_shape("assign to non-list/map index"),
                    }
                    return;
                }

                // Whole-value assign into an inout param: value must outlive
                // this function's scratch arena. Loop-carried locals (declared
                // outside the outermost loop) escape to function scratch.
                //
                // §12 place-before-value: for Field targets whose base chain
                // contains an Index (`xs[i].f = v`), materialize the place
                // (and fire its bounds/key check) BEFORE evaluating the RHS.
                // Zig assignment does not guarantee LHS-before-RHS evaluation
                // of a single `lhs = rhs;` statement, so Index places are
                // hoisted to a preceding `const` inside `place_lvalue`.
                let (lhs, val) = match target {
                    Place::Var(n) => {
                        let val = if self.inouts.contains(n) {
                            if is_container_ty(&value.ty) {
                                self.store_to(value, &format!("{n}.*.alloc"), true)
                            } else if needs_dup(&value.ty) {
                                // TODO(stage2c): per-inout allocator for forwarded non-container inouts.
                                // Tracked residual of the honest-arena overhaul (decision-log
                                // 2026-07-24): ret_alloc retention here is safe (call-site re-homing
                                // composes through forwarding) but over-retains; the fix is an
                                // allocator threaded per inout param, gated like the other stages.
                                self.store_to(value, "_sudo_ret_alloc", true)
                            } else {
                                self.store(value)
                            }
                        } else if !*declares && self.escapes_loop(n) {
                            // Loop-carried reassignment: escape into function scratch
                            // so the value survives the per-iteration reset.
                            let dest = self.scratch_alloc();
                            self.store_to(value, &dest, true)
                        } else {
                            self.store(value)
                        };
                        (self.place_lvalue(target), val)
                    }
                    // Field assignment routes the RHS to the record ROOT's
                    // lifetime, mirroring the Var/Index destination routing.
                    // Without this, `h.xs = [..]` through an inout param (or a
                    // loop-carried local) builds the value in this function's
                    // transient scratch / loop arena and dangles once that arena
                    // is freed — a UAF crash or silent garbage. (F1)
                    Place::Field { base, .. } => {
                        let esc = self.place_escapes(base);
                        // Place first (§12): Index chain materializes here.
                        // Single call so the index expression is evaluated once
                        // (also used below for container `.alloc` routing).
                        let lhs = self.place_lvalue(target);
                        let val = if is_container_ty(&value.ty) {
                            // A container field carries its own allocator; copy
                            // the new value into wherever the field already
                            // lives (the record root's true home).
                            self.store_to(value, &format!("{lhs}.alloc"), esc)
                        } else if needs_dup(&value.ty) && esc {
                            // Non-container composite whose record root escapes
                            // this function/iteration: re-home like the Var case
                            // — inout → the caller's return allocator; loop-
                            // carried local → function scratch.
                            let is_inout = place_root_local(base)
                                .is_some_and(|n| self.inouts.contains(n));
                            if is_inout {
                                self.store_to(value, "_sudo_ret_alloc", true)
                            } else {
                                let dest = self.scratch_alloc();
                                self.store_to(value, &dest, true)
                            }
                        } else {
                            self.store(value)
                        };
                        (lhs, val)
                    }
                    Place::Index { .. } => {
                        // Bare Index assign returned early above.
                        (self.place_lvalue(target), self.store(value))
                    }
                };
                if *declares {
                    let ty = zig_ty(&value.ty);
                    self.line(&format!("var {lhs}: {ty} = {val};"));
                    // Zig 0.16: unused mutation of `var` is a hard error.
                    self.line(&format!("_ = &{lhs};"));
                    if let Place::Var(n) = target {
                        self.note_declared(n);
                    }
                } else {
                    self.line(&format!("{lhs} = {val};"));
                }
            }
            IrStmt::TupleAssign {
                targets,
                declares,
                value,
            } => {
                let tup = self.store(value);
                let tmp = self.tmp("tup");
                let ty = zig_ty(&value.ty);
                self.line(&format!("const {tmp}: {ty} = {tup};"));
                if let Ty::Tuple(ts) = &value.ty {
                    for (i, (name, decl)) in targets.iter().zip(declares.iter()).enumerate() {
                        let elem_ty = &ts[i];
                        let src = format!("{tmp}.f{i}");
                        let alloc = if !*decl && self.escapes_loop(name) {
                            self.scratch_alloc()
                        } else {
                            self.cur_alloc()
                        };
                        let owned = if needs_dup(elem_ty) {
                            format!("copy_{}({}, {src})", mangle(elem_ty), alloc)
                        } else {
                            src
                        };
                        if *decl {
                            self.line(&format!("var {name}: {} = {owned};", zig_ty(elem_ty)));
                            self.line(&format!("_ = &{name};"));
                            self.note_declared(name);
                        } else {
                            self.line(&format!("{name} = {owned};"));
                        }
                    }
                } else {
                    unreachable_shape("TupleAssign non-tuple");
                }
            }
            IrStmt::Expr(e) => {
                let v = self.expr(e);
                // Void-producing expressions (mutating builtins, re-homed void
                // calls) already emit their effect and return the placeholder
                // `"{}"` — do not emit a noisy `_ = {};`.
                if v != "{}" {
                    self.line(&format!("_ = {v};"));
                }
            }
            IrStmt::If { arms, else_block } => {
                self.emit_if_chain(arms, else_block.as_deref(), 0);
            }
            IrStmt::While { cond, body } => {
                let created = self.enter_loop(body);
                // Outermost loop: force `while (true)` so the per-iteration
                // reset runs before condition evaluation (condition transients
                // then live in the loop arena). Nested loops keep the existing form.
                // Elided-arena, non-trapping loops fall through to plain `while (cond)`.
                if created.is_some() || can_trap(cond) {
                    self.line("while (true) {");
                    self.indent += 1;
                    if let Some(a) = &created {
                        self.line(&format!("rt.loopReset(&{a});"));
                    }
                    let c = self.expr(cond);
                    self.line(&format!("if (!({c})) break;"));
                    self.emit_stmts(body);
                    self.indent -= 1;
                    self.line("}");
                } else {
                    let c = self.expr(cond);
                    self.line(&format!("while ({c}) {{"));
                    self.indent += 1;
                    self.emit_stmts(body);
                    self.indent -= 1;
                    self.line("}");
                }
                self.exit_loop();
            }
            IrStmt::ForRange {
                var,
                from,
                to,
                down,
                body,
            } => {
                // Wrap the whole loop in its own block so the loop variable (and
                // the lo/hi/done temps and any per-loop arena) is freshly scoped
                // to this loop — §5.3. Without it, two sequential `for i` loops
                // in one scope redeclare `i` and Zig 0.16 rejects the build. (F7)
                self.line("{");
                self.indent += 1;
                let created = self.enter_loop(body);
                let lo = self.expr(from);
                let hi = self.expr(to);
                let lo_t = self.tmp("lo");
                let hi_t = self.tmp("hi");
                let done = self.tmp("done");
                self.line(&format!("const {lo_t}: i64 = {lo};"));
                self.line(&format!("const {hi_t}: i64 = {hi};"));
                self.line(&format!("var {var}: i64 = {lo_t};"));
                self.line(&format!("_ = &{var};"));
                self.note_declared(var);
                if *down {
                    self.line(&format!("var {done} = !({lo_t} >= {hi_t});"));
                    self.line(&format!("_ = &{done};"));
                    self.line(&format!("while (!{done}) : ({var} -%= 1) {{"));
                } else {
                    self.line(&format!("var {done} = !({lo_t} <= {hi_t});"));
                    self.line(&format!("_ = &{done};"));
                    self.line(&format!("while (!{done}) : ({var} +%= 1) {{"));
                }
                self.indent += 1;
                if let Some(a) = &created {
                    self.line(&format!("rt.loopReset(&{a});"));
                }
                self.line(&format!("{done} = ({var} == {hi_t});"));
                self.emit_stmts(body);
                self.indent -= 1;
                self.line("}");
                self.exit_loop();
                self.indent -= 1;
                self.line("}");
            }
            IrStmt::ForIn { vars, iter, body } => {
                self.emit_for_in(vars, iter, body);
            }
            IrStmt::Match { scrutinee, arms } => {
                self.emit_match(scrutinee, arms);
            }
            IrStmt::Return(None) => self.line("return;"),
            IrStmt::Return(Some(e)) => {
                // Escape into caller-owned ret_alloc (must outlive scratch).
                let v = self.store_to(e, "_sudo_ret_alloc", true);
                self.line(&format!("return {v};"));
            }
            IrStmt::Assert { cond, line } => self.emit_assert(cond, *line),
            IrStmt::Skip => {}
            IrStmt::Break => self.line("break;"),
            IrStmt::Continue => self.line("continue;"),
            IrStmt::ExpectTrap { kind, body, line } => self.emit_expect_trap(kind, body, *line),
        }
    }

    /// Emit `if` / nested `else { if ... }` chains so short-circuit temps from
    /// `else if` conditions stay in a scope that is still open when they are
    /// read (flat `else if` would declare them inside the preceding arm).
    fn emit_if_chain(
        &mut self,
        arms: &[(IrExpr, Vec<IrStmt>)],
        else_block: Option<&[IrStmt]>,
        idx: usize,
    ) {
        let (cond, body) = &arms[idx];
        let c = self.expr(cond);
        self.line(&format!("if ({c}) {{"));
        self.indent += 1;
        self.emit_stmts(body);
        self.indent -= 1;
        if idx + 1 < arms.len() {
            self.line("} else {");
            self.indent += 1;
            self.emit_if_chain(arms, else_block, idx + 1);
            self.indent -= 1;
            self.line("}");
        } else if let Some(eb) = else_block {
            self.line("} else {");
            self.indent += 1;
            self.emit_stmts(eb);
            self.indent -= 1;
            self.line("}");
        } else {
            self.line("}");
        }
    }

    /// `expect_trap Kind` observes a trap locally. The body is lowered inline
    /// into a labeled block that yields `?rt.SudoError` — fallible ops break to
    /// the label carrying the error instead of `try`/`return`-ing out of the
    /// test. A labeled block is an ordinary scope, so the body sees enclosing
    /// locals exactly as normal code does (Zig nested fns, by contrast, do NOT
    /// close over outer locals — see notes/friction-zig.md).
    fn emit_expect_trap(&mut self, kind: &str, body: &[IrStmt], line: u32) {
        let trap = self.tmp("trap");
        let label = self.tmp("et");
        let e = self.tmp("e");
        self.line(&format!("const {trap}: ?rt.SudoError = {label}: {{"));
        self.indent += 1;
        let saved = self.trap_label.replace(label.clone());
        self.emit_stmts(body);
        self.trap_label = saved;
        self.line(&format!("break :{label} null;"));
        self.indent -= 1;
        self.line("};");
        self.line(&format!("if ({trap}) |{e}| {{"));
        self.indent += 1;
        self.line(&format!(
            "if ({e} != rt.SudoError.{kind}) return rt.expectTrapWrong({line}, \"{kind}\", @errorName({e}));"
        ));
        self.indent -= 1;
        self.line(&format!("}} else return rt.expectTrapNone({line}, \"{kind}\");"));
    }

    fn emit_for_in(&mut self, vars: &[String], iter: &IrExpr, body: &[IrStmt]) {
        // Snapshot the collection so mutating it in the body cannot affect the
        // iteration. The snapshot must live in the ENCLOSING allocator (it
        // spans all iterations); enter the loop arena only after emitting it.
        // Loop bindings are fresh owned copies (value semantics); emit them as
        // `var … ; _ = &name;` so unused / never-mutated bindings are not
        // Zig 0.16 compile errors.
        let coll = self.expr(iter);
        let snap = self.tmp("snap");
        let snap_ty = zig_ty(&iter.ty);
        let snap_val = if needs_dup(&iter.ty) {
            format!("copy_{}({}, {coll})", mangle(&iter.ty), self.cur_alloc())
        } else {
            coll
        };
        self.line(&format!("var {snap}: {snap_ty} = {snap_val};"));
        self.line(&format!("_ = &{snap};"));
        let created = self.enter_loop(body);
        match &iter.ty {
            Ty::List(elem) => {
                let vname = &vars[0];
                self.line(&format!("for ({snap}.items()) |{vname}_ref| {{"));
                self.indent += 1;
                if let Some(a) = &created {
                    self.line(&format!("rt.loopReset(&{a});"));
                }
                self.bind_loop_var(vname, elem, &format!("{vname}_ref"));
                self.emit_stmts(body);
                self.indent -= 1;
                self.line("}");
            }
            Ty::Set(elem) => {
                let it = self.tmp("it");
                self.line(&format!("var {it} = {snap}.map.valueIterator();"));
                self.line(&format!("while ({it}.next()) |ep| {{"));
                self.indent += 1;
                if let Some(a) = &created {
                    self.line(&format!("rt.loopReset(&{a});"));
                }
                self.bind_loop_var(&vars[0], elem, "ep.*");
                self.emit_stmts(body);
                self.indent -= 1;
                self.line("}");
            }
            Ty::Map(k, v) => {
                let it = self.tmp("it");
                self.line(&format!("var {it} = {snap}.map.valueIterator();"));
                self.line(&format!("while ({it}.next()) |kv| {{"));
                self.indent += 1;
                if let Some(a) = &created {
                    self.line(&format!("rt.loopReset(&{a});"));
                }
                self.bind_loop_var(&vars[0], k, "kv.k");
                if vars.len() >= 2 {
                    self.bind_loop_var(&vars[1], v, "kv.v");
                }
                self.emit_stmts(body);
                self.indent -= 1;
                self.line("}");
            }
            other => unreachable_shape(&format!("stmt ForIn on {other}")),
        }
        self.exit_loop();
    }

    /// Bind a for-in loop variable to an owned copy of the current element.
    fn bind_loop_var(&mut self, name: &str, elem_ty: &Ty, src: &str) {
        let owned = copy_expr(elem_ty, src, &self.cur_alloc());
        self.line(&format!("var {name} = {owned};"));
        self.line(&format!("_ = &{name};"));
        self.note_declared(name);
    }

    fn emit_match(&mut self, scrutinee: &IrExpr, arms: &[IrMatchArm]) {
        let s = self.expr(scrutinee);
        let s_tmp = self.tmp("scrut");
        self.line(&format!("const {s_tmp} = {s};"));

        match &scrutinee.ty {
            Ty::Int | Ty::Bool => {
                self.line(&format!("switch ({s_tmp}) {{"));
                self.indent += 1;
                let mut has_else = false;
                let mut saw_true = false;
                let mut saw_false = false;
                let mut seen_ints: std::collections::HashSet<i64> =
                    std::collections::HashSet::new();
                for arm in arms {
                    match &arm.pattern {
                        IrPattern::Int(v) => {
                            // First-matching-case-wins (spec §6.3): a later
                            // arm whose literal already appeared is dead
                            // code. A Zig `switch` can't express that with a
                            // duplicate case value, so drop it.
                            if !seen_ints.insert(*v) {
                                continue;
                            }
                            self.line(&format!("{v} => {{"));
                            self.indent += 1;
                            self.emit_stmts(&arm.body);
                            self.indent -= 1;
                            self.line("},");
                        }
                        IrPattern::Bool(v) => {
                            // Same first-wins dedup, for the bool literal
                            // that's already been seen.
                            if *v {
                                if saw_true {
                                    continue;
                                }
                                saw_true = true;
                            } else {
                                if saw_false {
                                    continue;
                                }
                                saw_false = true;
                            }
                            self.line(&format!("{v} => {{"));
                            self.indent += 1;
                            self.emit_stmts(&arm.body);
                            self.indent -= 1;
                            self.line("},");
                        }
                        IrPattern::Wildcard => {
                            has_else = true;
                            self.line("else => {");
                            self.indent += 1;
                            self.emit_stmts(&arm.body);
                            self.indent -= 1;
                            self.line("},");
                        }
                        IrPattern::Variant { .. } => {
                            unreachable_shape("int/bool match with variant pattern")
                        }
                    }
                }
                // Zig switches must be exhaustive: i64 always needs an else;
                // bool needs one unless both values are covered explicitly.
                let bool_exhaustive =
                    matches!(scrutinee.ty, Ty::Bool) && saw_true && saw_false;
                if !has_else && !bool_exhaustive {
                    self.line("else => {},");
                }
                self.indent -= 1;
                self.line("}");
            }
            Ty::Enum(ename) => {
                let edef = self.m.enum_(ename).expect("enum");
                self.line(&format!("switch ({s_tmp}) {{"));
                self.indent += 1;
                let mut has_else = false;
                for arm in arms {
                    match &arm.pattern {
                        IrPattern::Wildcard => {
                            has_else = true;
                            self.line("else => {");
                            self.indent += 1;
                            self.emit_stmts(&arm.body);
                            self.indent -= 1;
                            self.line("},");
                        }
                        IrPattern::Variant {
                            variant, binders, ..
                        } => {
                            let vdef = edef
                                .variants
                                .iter()
                                .find(|v| v.name == *variant)
                                .expect("variant");
                            if vdef.fields.is_empty() {
                                self.line(&format!(".{variant} => {{"));
                                self.indent += 1;
                                self.emit_stmts(&arm.body);
                                self.indent -= 1;
                                self.line("},");
                            } else if vdef.fields.len() == 1 {
                                let fty = &vdef.fields[0].ty;
                                let b = &binders[0];
                                self.line(&format!(".{variant} => |{b}_p| {{"));
                                self.indent += 1;
                                if boxed_in_payload(fty) {
                                    let owned = if needs_dup(fty) {
                                        let a = self.cur_alloc();
                                        format!("copy_{}({a}, {b}_p.*)", mangle(fty))
                                    } else {
                                        format!("{b}_p.*")
                                    };
                                    self.line(&format!("const {b} = {owned};"));
                                } else if needs_dup(fty) {
                                    let a = self.cur_alloc();
                                    self.line(&format!(
                                        "const {b} = copy_{}({a}, {b}_p);",
                                        mangle(fty),
                                    ));
                                } else {
                                    self.line(&format!("const {b} = {b}_p;"));
                                }
                                if !binder_used(&arm.body, b) {
                                    self.line(&format!("_ = {b};"));
                                }
                                self.emit_stmts(&arm.body);
                                self.indent -= 1;
                                self.line("},");
                            } else {
                                self.line(&format!(".{variant} => |{variant}_p| {{"));
                                self.indent += 1;
                                for (i, f) in vdef.fields.iter().enumerate() {
                                    let fname = &f.name;
                                    let fty = &f.ty;
                                    let b = &binders[i];
                                    if boxed_in_payload(fty) {
                                        let owned = if needs_dup(fty) {
                                            let a = self.cur_alloc();
                                            format!(
                                                "copy_{}({a}, {variant}_p.{fname}.*)",
                                                mangle(fty),
                                            )
                                        } else {
                                            format!("{variant}_p.{fname}.*")
                                        };
                                        self.line(&format!("const {b} = {owned};"));
                                    } else if needs_dup(fty) {
                                        let a = self.cur_alloc();
                                        self.line(&format!(
                                            "const {b} = copy_{}({a}, {variant}_p.{fname});",
                                            mangle(fty),
                                        ));
                                    } else {
                                        self.line(&format!(
                                            "const {b} = {variant}_p.{fname};"
                                        ));
                                    }
                                    if !binder_used(&arm.body, b) {
                                        self.line(&format!("_ = {b};"));
                                    }
                                }
                                self.emit_stmts(&arm.body);
                                self.indent -= 1;
                                self.line("},");
                            }
                        }
                        IrPattern::Int(_) | IrPattern::Bool(_) => {
                            unreachable_shape("enum match with scalar pattern")
                        }
                    }
                }
                // Enum matches are exhaustive (checker-guaranteed); a Zig `else`
                // is emitted only when the sudo match used a wildcard.
                let _ = has_else;
                self.indent -= 1;
                self.line("}");
            }
            Ty::Option_(inner) => {
                // Two-way: Some binder / None / wildcard.
                let mut some_arm: Option<&IrMatchArm> = None;
                let mut none_arm: Option<&IrMatchArm> = None;
                let mut wild_arm: Option<&IrMatchArm> = None;
                for arm in arms {
                    match &arm.pattern {
                        IrPattern::Variant { variant, .. } if variant == "Some" => {
                            some_arm = Some(arm);
                        }
                        IrPattern::Variant { variant, .. } if variant == "None" => {
                            none_arm = Some(arm);
                        }
                        IrPattern::Wildcard => wild_arm = Some(arm),
                        _ => {}
                    }
                }
                self.line(&format!("if ({s_tmp}) |__opt_p| {{"));
                self.indent += 1;
                if let Some(arm) = some_arm {
                    if let IrPattern::Variant { binders, .. } = &arm.pattern {
                        let b = &binders[0];
                        if boxed_in_payload(inner) {
                            let owned = if needs_dup(inner) {
                                let a = self.cur_alloc();
                                format!("copy_{}({a}, __opt_p.*)", mangle(inner))
                            } else {
                                "__opt_p.*".into()
                            };
                            self.line(&format!("const {b} = {owned};"));
                        } else if needs_dup(inner) {
                            let a = self.cur_alloc();
                            self.line(&format!(
                                "const {b} = copy_{}({a}, __opt_p);",
                                mangle(inner),
                            ));
                        } else {
                            self.line(&format!("const {b} = __opt_p;"));
                        }
                        if !binder_used(&arm.body, b) {
                            self.line(&format!("_ = {b};"));
                        }
                    }
                    self.emit_stmts(&arm.body);
                } else if let Some(arm) = wild_arm {
                    self.emit_stmts(&arm.body);
                }
                self.indent -= 1;
                self.line("} else {");
                self.indent += 1;
                if let Some(arm) = none_arm {
                    self.emit_stmts(&arm.body);
                } else if let Some(arm) = wild_arm {
                    // wildcard only fires once — if Some already used it, skip
                    if some_arm.is_none() {
                        self.emit_stmts(&arm.body);
                    }
                }
                self.indent -= 1;
                self.line("}");
            }
            Ty::Result_(ok, err) => {
                self.line(&format!("switch ({s_tmp}) {{"));
                self.indent += 1;
                let mut has_else = false;
                for arm in arms {
                    match &arm.pattern {
                        IrPattern::Wildcard => {
                            has_else = true;
                            self.line("else => {");
                            self.indent += 1;
                            self.emit_stmts(&arm.body);
                            self.indent -= 1;
                            self.line("},");
                        }
                        IrPattern::Variant {
                            variant, binders, ..
                        } => {
                            let (side_ty, tag) = if variant == "Ok" {
                                (ok.as_ref(), "Ok")
                            } else {
                                (err.as_ref(), "Err")
                            };
                            let b = &binders[0];
                            self.line(&format!(".{tag} => |{b}_p| {{"));
                            self.indent += 1;
                            if boxed_in_payload(side_ty) {
                                let owned = if needs_dup(side_ty) {
                                    let a = self.cur_alloc();
                                    format!("copy_{}({a}, {b}_p.*)", mangle(side_ty))
                                } else {
                                    format!("{b}_p.*")
                                };
                                self.line(&format!("const {b} = {owned};"));
                            } else if needs_dup(side_ty) {
                                let a = self.cur_alloc();
                                self.line(&format!(
                                    "const {b} = copy_{}({a}, {b}_p);",
                                    mangle(side_ty),
                                ));
                            } else {
                                self.line(&format!("const {b} = {b}_p;"));
                            }
                            if !binder_used(&arm.body, b) {
                                self.line(&format!("_ = {b};"));
                            }
                            self.emit_stmts(&arm.body);
                            self.indent -= 1;
                            self.line("},");
                        }
                        _ => unreachable_shape("result match pattern"),
                    }
                }
                // Ok/Err are exhaustive; emit `else` only for a wildcard arm.
                let _ = has_else;
                self.indent -= 1;
                self.line("}");
            }
            other => unreachable_shape(&format!("match on {other}")),
        }
    }

    fn emit_assert(&mut self, cond: &IrExpr, line: u32) {
        if let IrExprKind::Binary {
            op: BinaryOp::Eq,
            lhs,
            rhs,
        } = &cond.kind
        {
            if is_scalar(&lhs.ty) && is_scalar(&rhs.ty) {
                let l = self.expr(lhs);
                let r = self.expr(rhs);
                let helper = match &lhs.ty {
                    Ty::Int => "assertEqI64",
                    Ty::Float => "assertEqF64",
                    Ty::Bool => "assertEqBool",
                    _ => unreachable!(),
                };
                self.try_line(&format!("rt.{helper}({l}, {r}, {line})"));
                return;
            }
            // Composite equality with canon diagnostics.
            if !is_scalar(&lhs.ty)
                && !matches!(lhs.ty, Ty::Func { .. } | Ty::Map(..) | Ty::Set(_))
            {
                let l = self.expr(lhs);
                let r = self.expr(rhs);
                let mn = mangle(&lhs.ty);
                self.line(&format!("if (!eq_{mn}({l}, {r})) {{"));
                self.indent += 1;
                self.line("rt.det_reset();");
                self.line(&format!("rt.det_line_prefix({line});"));
                self.line(&format!("canon_{mn}({l});"));
                self.line("rt.det_str(\" != \");");
                self.line(&format!("canon_{mn}({r});"));
                let raise = self.raise("rt.SudoError.AssertFailed");
                self.line(&format!("{raise};"));
                self.indent -= 1;
                self.line("}");
                return;
            }
        }
        let c = self.expr(cond);
        let raise = self.raise("rt.SudoError.AssertFailed");
        self.line(&format!("if (!({c})) {raise};"));
    }

    /// Copy `e` into allocator expression `dest`. `escaping` = the destination
    /// outlives the current scratch scope (return value / inout / longer-lived
    /// container) → must deep-copy even a freshly-built (non-aliasing) value,
    /// because it currently lives in the shorter-lived scratch.
    fn store_to(&mut self, e: &IrExpr, dest: &str, escaping: bool) -> String {
        if !needs_dup(&e.ty) {
            return self.expr(e);
        }
        if escaping || aliasing(&e.kind) {
            if dest == "_sudo_ret_alloc" {
                self.ret_alloc_used = true;
            }
            let v = self.expr(e);
            format!("copy_{}({dest}, {v})", mangle(&e.ty))
        } else {
            self.expr(e)
        }
    }

    /// Storing-position expression into the current scratch (or global outside
    /// function bodies): deep-copy aliasing managed reads; fresh values pass through.
    fn store(&mut self, e: &IrExpr) -> String {
        let a = self.cur_alloc();
        self.store_to(e, &a, false)
    }

    /// Expression → Zig source fragment. May emit preceding statements (temps)
    /// at the current indent when statement-lowering is required (lazy and/or).
    fn expr(&mut self, e: &IrExpr) -> String {
        match &e.kind {
            IrExprKind::Int(v) => format!("{v}"),
            IrExprKind::Float(v) => format_float(*v),
            IrExprKind::Bool(v) => {
                if *v {
                    "true".into()
                } else {
                    "false".into()
                }
            }
            IrExprKind::Text(chars) => {
                // Text is List<int> of code points.
                let t = self.tmp("txt");
                let ty = zig_ty(&e.ty);
                let a = self.cur_alloc();
                self.line(&format!("var {t}: {ty} = .{{ .alloc = {a} }};"));
                self.line(&format!("_ = &{t};"));
                for c in chars {
                    self.line(&format!("{t}.append({c}) catch @panic(\"sudo: arena OOM\");"));
                }
                t
            }
            IrExprKind::Local(n) => {
                if self.inouts.contains(n) || self.borrowed.contains(n) {
                    format!("{n}.*")
                } else {
                    n.clone()
                }
            }
            IrExprKind::Const(n) => n.clone(),
            IrExprKind::FuncRef(n) => format!("&{}", qualify_name(n)),
            IrExprKind::List(xs) => {
                let t = self.tmp("lst");
                let ty = zig_ty(&e.ty);
                let a = self.cur_alloc();
                self.line(&format!("var {t}: {ty} = .{{ .alloc = {a} }};"));
                self.line(&format!("_ = &{t};"));
                for x in xs {
                    let v = self.store(x);
                    self.line(&format!("{t}.append({v}) catch @panic(\"sudo: arena OOM\");"));
                }
                t
            }
            IrExprKind::Tuple(xs) => {
                let mut fields = Vec::new();
                for (i, x) in xs.iter().enumerate() {
                    fields.push(format!(".f{i} = {}", self.store(x)));
                }
                let ty = zig_ty(&e.ty);
                format!("@as({ty}, .{{ {} }})", fields.join(", "))
            }
            IrExprKind::CallFunc { name, args } => self.emit_call(name, args),
            IrExprKind::CallValue { callee, args } => {
                let c = self.expr(callee);
                let mut a: Vec<String> = vec![self.cur_alloc()];
                a.extend(args.iter().map(|x| self.store(x)));
                self.tryx(&format!("{c}({})", a.join(", ")))
            }
            IrExprKind::NewRecord { name, args } => {
                let r = self.m.record(name).expect("record");
                let mut fields = Vec::new();
                for (field, a) in r.fields.iter().zip(args.iter()) {
                let fname = &field.name;
                    fields.push(format!(".{fname} = {}", self.store(a)));
                }
                format!("@as({name}, .{{ {} }})", fields.join(", "))
            }
            IrExprKind::NewVariant {
                enum_name,
                variant,
                args,
            } => self.emit_new_variant(enum_name, variant, args, &e.ty),
            IrExprKind::Unary { op, operand } => self.emit_unary(*op, operand, &e.ty),
            IrExprKind::Binary { op, lhs, rhs } => self.emit_binary(*op, lhs, rhs, &e.ty),
            IrExprKind::Builtin { builtin, args } => self.emit_builtin(*builtin, args, &e.ty),
            IrExprKind::MutBuiltin {
                builtin,
                recv,
                recv_ty,
                args,
            } => self.emit_mut_builtin(*builtin, recv, recv_ty, args, &e.ty),
            IrExprKind::GetField { recv, name } => {
                let r = self.expr(recv);
                format!("{r}.{name}")
            }
            IrExprKind::Index { recv, index } => {
                let r = self.expr(recv);
                let i = self.expr(index);
                match &recv.ty {
                    Ty::List(_) => self.tryx(&format!("{r}.at({i})")),
                    Ty::Map(..) => self.tryx(&format!("{r}.index({i})")),
                    other => unreachable_shape(&format!("expr Index on {other}")),
                }
            }
        }
    }

    fn emit_new_variant(
        &mut self,
        enum_name: &str,
        variant: &str,
        args: &[IrExpr],
        result_ty: &Ty,
    ) -> String {
        let result_z = zig_ty(result_ty);
        // Option / Result are not user enums in the module table.
        if enum_name == "Option" {
            if variant == "None" {
                return format!("@as({result_z}, null)");
            }
            // Some(x)
            let inner = &args[0];
            let v = self.store(inner);
            if boxed_in_payload(&inner.ty) {
                return format!(
                    "@as({result_z}, rt.box({}, {}, {v}))",
                    self.cur_alloc(),
                    zig_ty(&inner.ty)
                );
            }
            return format!("@as({result_z}, {v})");
        }
        if enum_name == "Result" {
            let inner = &args[0];
            let v = self.store(inner);
            let payload = if boxed_in_payload(&inner.ty) {
                format!("rt.box({}, {}, {v})", self.cur_alloc(), zig_ty(&inner.ty))
            } else {
                v
            };
            return if variant == "Ok" {
                format!("@as({result_z}, .{{ .Ok = {payload} }})")
            } else {
                format!("@as({result_z}, .{{ .Err = {payload} }})")
            };
        }

        let edef = self.m.enum_(enum_name).expect("enum");
        let vdef = edef
            .variants
            .iter()
            .find(|v| v.name == variant)
            .expect("variant");
        if vdef.fields.is_empty() {
            format!("@as({result_z}, .{{ .{variant} = {{}} }})")
        } else if vdef.fields.len() == 1 {
            let fty = &vdef.fields[0].ty;
            let v = self.store(&args[0]);
            let payload = if boxed_in_payload(fty) {
                format!("rt.box({}, {}, {v})", self.cur_alloc(), zig_ty(fty))
            } else {
                v
            };
            format!("@as({result_z}, .{{ .{variant} = {payload} }})")
        } else {
            let mut fields = Vec::new();
            for (field, a) in vdef.fields.iter().zip(args.iter()) {
            let fname = &field.name;
            let fty = &field.ty;
                let v = self.store(a);
                let payload = if boxed_in_payload(fty) {
                    format!("rt.box({}, {}, {v})", self.cur_alloc(), zig_ty(fty))
                } else {
                    v
                };
                fields.push(format!(".{fname} = {payload}"));
            }
            format!(
                "@as({result_z}, .{{ .{variant} = .{{ {} }} }})",
                fields.join(", ")
            )
        }
    }

    fn emit_unary(&mut self, op: UnaryOp, operand: &IrExpr, ty: &Ty) -> String {
        let x = self.expr(operand);
        match op {
            UnaryOp::Neg => match ty {
                Ty::Int => self.tryx(&format!("rt.neg({x})")),
                Ty::Float => format!("(-{x})"),
                _ => unreachable!("neg on non-numeric"),
            },
            UnaryOp::Not => format!("(!{x})"),
        }
    }

    fn emit_binary(&mut self, op: BinaryOp, lhs: &IrExpr, rhs: &IrExpr, ty: &Ty) -> String {
        if matches!(op, BinaryOp::And | BinaryOp::Or) {
            if can_trap(rhs) {
                return self.emit_lazy_bool(op, lhs, rhs);
            }
            let l = self.expr(lhs);
            let r = self.expr(rhs);
            let kw = if op == BinaryOp::And { "and" } else { "or" };
            return format!("({l} {kw} {r})");
        }

        // Composite == / !=
        if matches!(op, BinaryOp::Eq | BinaryOp::Ne) && !is_scalar(&lhs.ty) {
            let l = self.expr(lhs);
            let r = self.expr(rhs);
            if matches!(lhs.ty, Ty::Func { .. }) {
                return if op == BinaryOp::Eq {
                    format!("({l} == {r})")
                } else {
                    format!("({l} != {r})")
                };
            }
            let eq = format!("eq_{}({l}, {r})", mangle(&lhs.ty));
            return if op == BinaryOp::Eq {
                format!("({eq})")
            } else {
                format!("(!{eq})")
            };
        }

        // List (and text) concatenation.
        if matches!(op, BinaryOp::Add) && matches!(ty, Ty::List(_)) {
            return self.emit_list_concat(lhs, rhs, ty);
        }

        let l = self.expr(lhs);
        let r = self.expr(rhs);

        if matches!(ty, Ty::Int) {
            match op {
                BinaryOp::Add => return self.tryx(&format!("rt.add({l}, {r})")),
                BinaryOp::Sub => return self.tryx(&format!("rt.sub({l}, {r})")),
                BinaryOp::Mul => return self.tryx(&format!("rt.mul({l}, {r})")),
                BinaryOp::Div => return self.tryx(&format!("rt.divFloor({l}, {r})")),
                BinaryOp::Mod => return self.tryx(&format!("rt.modFloor({l}, {r})")),
                _ => {}
            }
        }

        if matches!(ty, Ty::Float) {
            // Routed through rt helpers so comptime-known operands are NOT folded
            // at Zig's extended `comptime_float` precision (would diverge from
            // IEEE binary64 per-op rounding, spec §4.2). (F5)
            match op {
                BinaryOp::Add => return format!("rt.fadd({l}, {r})"),
                BinaryOp::Sub => return format!("rt.fsub({l}, {r})"),
                BinaryOp::Mul => return format!("rt.fmul({l}, {r})"),
                BinaryOp::Div => return format!("rt.fdiv({l}, {r})"),
                _ => {}
            }
        }

        let sym = match op {
            BinaryOp::Lt => "<",
            BinaryOp::Le => "<=",
            BinaryOp::Gt => ">",
            BinaryOp::Ge => ">=",
            BinaryOp::Eq => "==",
            BinaryOp::Ne => "!=",
            BinaryOp::Add
            | BinaryOp::Sub
            | BinaryOp::Mul
            | BinaryOp::Div
            | BinaryOp::Mod
            | BinaryOp::And
            | BinaryOp::Or => unreachable!("handled above"),
        };
        // Float comparisons: coerce both operands to f64 first so two near
        // literals that round to the same binary64 compare equal (Zig would
        // otherwise compare them at `comptime_float` precision). No-op for
        // runtime f64 operands. (F5)
        if matches!(lhs.ty, Ty::Float) {
            return format!("(@as(f64, {l}) {sym} @as(f64, {r}))");
        }
        format!("({l} {sym} {r})")
    }

    /// `a + b` on lists: a fresh list of deep-copied elements from each side.
    fn emit_list_concat(&mut self, lhs: &IrExpr, rhs: &IrExpr, ty: &Ty) -> String {
        let elem = match ty {
            Ty::List(e) => e.as_ref().clone(),
            _ => unreachable!("list concat result is a list"),
        };
        let l = self.expr(lhs);
        let lt = self.tmp("lcat");
        self.line(&format!("var {lt}: {} = {l};", zig_ty(&lhs.ty)));
        self.line(&format!("_ = &{lt};"));
        let r = self.expr(rhs);
        let rt = self.tmp("rcat");
        self.line(&format!("var {rt}: {} = {r};", zig_ty(&rhs.ty)));
        self.line(&format!("_ = &{rt};"));
        let out = self.tmp("cat");
        let a = self.cur_alloc();
        self.line(&format!("var {out}: {} = .{{ .alloc = {a} }};", zig_ty(ty)));
        self.line(&format!("_ = &{out};"));
        let copied = copy_expr(&elem, "x", &a);
        for src in [&lt, &rt] {
            self.line(&format!("for ({src}.items()) |x| {{"));
            self.indent += 1;
            self.line(&format!("{out}.append({copied}) catch @panic(\"sudo: arena OOM\");"));
            self.indent -= 1;
            self.line("}");
        }
        out
    }

    fn emit_lazy_bool(&mut self, op: BinaryOp, lhs: &IrExpr, rhs: &IrExpr) -> String {
        let t = self.tmp("b");
        let l = self.expr(lhs);
        self.line(&format!("var {t}: bool = {l};"));
        self.line(&format!("_ = &{t};"));
        match op {
            BinaryOp::And => {
                self.line(&format!("if ({t}) {{"));
                self.indent += 1;
                let r = self.expr(rhs);
                self.line(&format!("{t} = {r};"));
                self.indent -= 1;
                self.line("}");
            }
            BinaryOp::Or => {
                self.line(&format!("if (!{t}) {{"));
                self.indent += 1;
                let r = self.expr(rhs);
                self.line(&format!("{t} = {r};"));
                self.indent -= 1;
                self.line("}");
            }
            _ => unreachable!(),
        }
        t
    }

    fn emit_call(&mut self, name: &str, args: &[IrExpr]) -> String {
        let resolved = resolve_func_and_module_in(self.m, self.all, name);
        let inout_flags: Vec<bool> = resolved
            .map(|(_, f)| f.params.iter().map(|p| p.inout).collect())
            .unwrap_or_else(|| vec![false; args.len()]);
        let borrow_flags: Vec<bool> = match resolved {
            Some((owning, f)) => {
                let elig = func_borrow_eligible(f, owning, &self.address_taken);
                f.params.iter().map(|p| elig.contains(&p.name)).collect()
            }
            None => vec![false; args.len()],
        };

        // Guard 2: if a root local is BOTH an inout arg and mapped to a
        // borrow-eligible param in this SAME call, force the borrow-eligible
        // occurrence to fall back to a deep copy (a live borrow alongside an
        // in-flight inout mutation of the same storage would diverge from copy
        // semantics).
        let inout_roots: HashSet<&str> = args
            .iter()
            .zip(&inout_flags)
            .filter(|(_, &io)| io)
            .filter_map(|(a, _)| expr_root_var(a))
            .collect();

        let mut parts = Vec::new();
        for (i, arg) in args.iter().enumerate() {
            let is_inout = inout_flags.get(i).copied().unwrap_or(false);
            let is_borrow = borrow_flags.get(i).copied().unwrap_or(false);
            let shares_inout_root = expr_root_var(arg)
                .map(|r| inout_roots.contains(r))
                .unwrap_or(false);
            if is_inout {
                parts.push(self.expr_as_inout_arg(arg));
            } else if is_borrow && !shares_inout_root {
                parts.push(self.expr_as_borrow_arg(arg));
            } else if is_borrow {
                // Guard 2: same root local is also `inout` in this call. The
                // callee's param is still `*const T` (its signature does not
                // change per call site), but we must NOT alias the storage
                // being mutated in-flight by the inout arg — pass the address
                // of a FRESH deep copy instead.
                parts.push(self.materialize_borrow_copy(arg));
            } else {
                parts.push(self.store(arg));
            }
        }
        // A call passes `cur_alloc()` as the callee's result allocator, so a
        // callee that whole-value-replaces a NON-container composite `inout`
        // param (records/options/enums; containers carry their own `.alloc`)
        // builds the replacement in OUR cur_alloc. If that inout's storage
        // outlives cur_alloc — a loop-carried local, or a forwarded inout of
        // this function — it must be re-homed into its true-lifetime allocator
        // after the call, or a per-iteration reset frees it while it's live.
        // (stage2c) Re-homing composes through forwarding: each level copies
        // into its own escape allocator.
        let mut rehomes: Vec<(String, String)> = Vec::new();
        for (i, arg) in args.iter().enumerate() {
            if !inout_flags.get(i).copied().unwrap_or(false) {
                continue;
            }
            if !needs_dup(&arg.ty) || is_container_ty(&arg.ty) {
                continue;
            }
            let dest = match expr_root_var(arg) {
                Some(r) if self.inouts.contains(r) => {
                    self.ret_alloc_used = true;
                    "_sudo_ret_alloc".to_string()
                }
                Some(r) if self.escapes_loop(r) => self.scratch_alloc(),
                _ => continue, // storage lives in cur_alloc already — no re-home
            };
            let lv = self.expr(arg); // `n` or `n.*` — a valid lvalue too
            let copy = format!("copy_{}({dest}, {lv})", mangle(&arg.ty));
            rehomes.push((lv, copy));
        }

        let mut call_args = vec![self.cur_alloc()];
        call_args.extend(parts);
        let callee = qualify_name(name);
        let call = self.tryx(&format!("{callee}({})", call_args.join(", ")));
        if rehomes.is_empty() {
            return call;
        }
        // Re-homing needs the call to have executed, so emit it eagerly.
        let ret_void = resolved.map(|(_, f)| f.ret.is_none()).unwrap_or(false);
        let result = if ret_void {
            self.line(&format!("_ = {call};"));
            "{}".to_string()
        } else {
            let t = self.tmp("call");
            self.line(&format!("const {t} = {call};"));
            t
        };
        for (lv, copy) in rehomes {
            self.line(&format!("{lv} = {copy};"));
        }
        result
    }

    /// Deep-copy `e` into a named temp and return its address (`&tmp`).
    /// Used for borrow-eligible (`*const T`) params when we cannot pass a
    /// live borrow of the caller's storage (expr is not a simple place, or
    /// Guard 2 forces a non-aliasing copy).
    fn materialize_borrow_copy(&mut self, e: &IrExpr) -> String {
        let v = self.store(e);
        let t = self.tmp("barg");
        let ty = zig_ty(&e.ty);
        self.line(&format!("const {t}: {ty} = {v};"));
        format!("&{t}")
    }

    /// Address of `e` for a borrow-eligible (`*const T`) callee param.
    /// Locals that are already pointers (inout / borrowed) are forwarded;
    /// simple field places take `&place`; everything else is materialised
    /// into a named temp first so Zig has an addressable lvalue.
    fn expr_as_borrow_arg(&mut self, e: &IrExpr) -> String {
        match &e.kind {
            IrExprKind::Local(n) => {
                if self.borrowed.contains(n) || self.inouts.contains(n) {
                    n.clone()
                } else {
                    format!("&{n}")
                }
            }
            _ if is_simple_place(e) => {
                let place = simple_place(e);
                format!("&{}", self.place_lvalue(&place))
            }
            _ => self.materialize_borrow_copy(e),
        }
    }

    fn expr_as_inout_arg(&mut self, e: &IrExpr) -> String {
        let place = expr_as_place(e);
        let lv = self.place_lvalue(&place);
        if let Place::Var(n) = &place {
            if self.inouts.contains(n) {
                return n.clone();
            }
        }
        format!("&{lv}")
    }

    /// Lvalue expression for a place. For `Place::Index`, returns a pointer
    /// to the element via `atPtr`/`getPtr` (Zig auto-derefs for field access
    /// and assignment: `ptr.f = v`), materialised into a preceding `const`
    /// so the index is evaluated exactly once and any bounds/key trap fires
    /// as a statement before subsequent RHS evaluation (§12).
    fn place_lvalue(&mut self, p: &Place) -> String {
        match p {
            Place::Var(n) => {
                if self.inouts.contains(n) || self.borrowed.contains(n) {
                    format!("{n}.*")
                } else {
                    n.clone()
                }
            }
            Place::Index {
                base,
                base_ty,
                index,
            } => {
                // Same atPtr/getPtr pattern as `mut_recv_lvalue`, but hoisted
                // to a `const` so Field arms (`{b}.{name}`) compose through
                // auto-deref and §12 place-before-value holds when the caller
                // evaluates the place before the assigned value.
                let base_lv = self.place_lvalue(base);
                let idx = self.expr(index);
                let ptr = match base_ty {
                    Ty::List(_) => self.tryx(&format!("{base_lv}.atPtr({idx})")),
                    Ty::Map(..) => {
                        let raise = self.raise("rt.SudoError.KeyMissing");
                        format!("({base_lv}.getPtr({idx}) orelse {raise})")
                    }
                    other => unreachable_shape(&format!("place_lvalue Index on {other:?}")),
                };
                let t = self.tmp("pl");
                self.line(&format!("const {t} = {ptr};"));
                t
            }
            Place::Field { base, name, .. } => {
                let b = self.place_lvalue(base);
                format!("{b}.{name}")
            }
        }
    }

    /// Pointer to a place (for mutating list methods / put).
    fn place_ptr(&mut self, p: &Place) -> String {
        match p {
            Place::Var(n) => {
                if self.inouts.contains(n) {
                    // Already a `*T` parameter.
                    n.clone()
                } else {
                    format!("&{n}")
                }
            }
            Place::Field { base, name, .. } => {
                let b = self.place_lvalue(base);
                format!("&({b}.{name})")
            }
            // Index already yields a *T via atPtr/getPtr (const-hoisted); reuse
            // place_lvalue so m[k].sort() / xs[i].sort() / nested chains work
            // without an extra & (atPtr/getPtr already return pointers).
            Place::Index { .. } => self.place_lvalue(p),
        }
    }

    fn emit_builtin(&mut self, b: Builtin, args: &[IrExpr], result_ty: &Ty) -> String {
        match b {
            Builtin::AbsInt => {
                let a = self.expr(&args[0]);
                self.tryx(&format!("rt.absInt({a})"))
            }
            Builtin::AbsFloat => {
                let a = self.expr(&args[0]);
                format!("rt.absFloat({a})")
            }
            Builtin::MinInt => {
                let a = self.expr(&args[0]);
                let b = self.expr(&args[1]);
                format!("@min({a}, {b})")
            }
            Builtin::MaxInt => {
                let a = self.expr(&args[0]);
                let b = self.expr(&args[1]);
                format!("@max({a}, {b})")
            }
            Builtin::MinFloat => {
                let a = self.expr(&args[0]);
                let b = self.expr(&args[1]);
                format!("rt.fmin({a}, {b})")
            }
            Builtin::MaxFloat => {
                let a = self.expr(&args[0]);
                let b = self.expr(&args[1]);
                format!("rt.fmax({a}, {b})")
            }
            Builtin::FloatOfInt => {
                let a = self.expr(&args[0]);
                format!("rt.floatOfInt({a})")
            }
            Builtin::IntOfFloat => {
                let a = self.expr(&args[0]);
                self.tryx(&format!("rt.intOfFloat({a})"))
            }
            Builtin::Floor => {
                let a = self.expr(&args[0]);
                format!("rt.floor({a})")
            }
            Builtin::Ceil => {
                let a = self.expr(&args[0]);
                format!("rt.ceil({a})")
            }
            Builtin::Round => {
                let a = self.expr(&args[0]);
                format!("rt.round({a})")
            }
            Builtin::Sqrt => {
                let a = self.expr(&args[0]);
                format!("rt.sqrt({a})")
            }
            Builtin::Filled => {
                // filled(n, value) → List. §12 CBV: both arguments evaluate
                // left-to-right BEFORE the builtin's own InvalidArg
                // precondition is checked, so a trap in the fill value fires
                // even when n < 0, and even when n == 0 (nothing is stored).
                // Bind both to consts, in argument order, before the check.
                let n = self.expr(&args[0]);
                let n_t = self.tmp("n");
                self.line(&format!("const {n_t}: i64 = {n};"));
                let v_expr = self.store(&args[1]);
                let v_t = self.tmp("fillv");
                let elem_ty = match result_ty {
                    Ty::List(e) => zig_ty(e),
                    _ => "i64".to_string(),
                };
                self.line(&format!("const {v_t}: {elem_ty} = {v_expr};"));
                let raise = self.raise("rt.SudoError.InvalidArg");
                self.line(&format!("if ({n_t} < 0) {raise};"));
                let t = self.tmp("filled");
                let ty = zig_ty(result_ty);
                let a = self.cur_alloc();
                self.line(&format!("var {t}: {ty} = .{{ .alloc = {a} }};"));
                self.line(&format!("_ = &{t};"));
                let i = self.tmp("i");
                self.line(&format!("var {i}: i64 = 0;"));
                self.line(&format!("_ = &{i};"));
                self.line(&format!("while ({i} < {n_t}) : ({i} +%= 1) {{"));
                self.indent += 1;
                self.line(&format!("{t}.append({v_t}) catch @panic(\"sudo: arena OOM\");"));
                self.indent -= 1;
                self.line("}");
                t
            }
            Builtin::ListLength => {
                let a = self.expr(&args[0]);
                format!("{a}.len()")
            }
            Builtin::OptIsSome => {
                let a = self.expr(&args[0]);
                format!("({a} != null)")
            }
            Builtin::OptIsNone => {
                let a = self.expr(&args[0]);
                format!("({a} == null)")
            }
            Builtin::OptUnwrap => {
                let a = self.expr(&args[0]);
                let raise = self.raise("rt.SudoError.UnwrapFailed");
                // Boxed payloads deref after the null check.
                if matches!(&args[0].ty, Ty::Option_(inner) if boxed_in_payload(inner)) {
                    format!("(({a} orelse {raise}).*)")
                } else {
                    format!("({a} orelse {raise})")
                }
            }
            Builtin::OptGetOr => {
                let a = self.expr(&args[0]);
                let d = self.store(&args[1]);
                if let Ty::Option_(inner) = &args[0].ty {
                    if boxed_in_payload(inner) {
                        // `?*const T` vs default `T` — branch explicitly.
                        let t = self.tmp("og");
                        let ty = zig_ty(inner);
                        self.line(&format!("const {t}: {ty} = if ({a}) |p| p.* else {d};"));
                        t
                    } else {
                        format!("({a} orelse {d})")
                    }
                } else {
                    format!("({a} orelse {d})")
                }
            }
            Builtin::ResIsOk => {
                let a = self.expr(&args[0]);
                // Tag check via switch — more portable than `v == .Ok` across Zig
                // versions when the union carries payloads.
                let t = self.tmp("isok");
                self.line(&format!("const {t}: bool = switch ({a}) {{ .Ok => true, .Err => false }};"));
                t
            }
            Builtin::ResIsErr => {
                let a = self.expr(&args[0]);
                let t = self.tmp("iserr");
                self.line(&format!("const {t}: bool = switch ({a}) {{ .Ok => false, .Err => true }};"));
                t
            }
            Builtin::ResUnwrap => {
                let a = self.expr(&args[0]);
                let t = self.tmp("ru");
                // Need the Ok payload type from result_ty… actually unwrap
                // returns the Ok side. Infer from args[0].ty.
                if let Ty::Result_(ok, _) = &args[0].ty {
                    let ok_z = zig_ty(ok);
                    self.line(&format!("const {t}: {ok_z} = switch ({a}) {{"));
                    self.indent += 1;
                    if boxed_in_payload(ok) {
                        self.line(".Ok => |p| p.*,");
                    } else {
                        self.line(".Ok => |x| x,");
                    }
                    let raise = self.raise("rt.SudoError.UnwrapFailed");
                    self.line(&format!(".Err => {raise},"));
                    self.indent -= 1;
                    self.line("};");
                    t
                } else {
                    unreachable_shape("ResUnwrap non-result")
                }
            }
            Builtin::ResGetOr => {
                let a = self.expr(&args[0]);
                let d = self.store(&args[1]);
                let t = self.tmp("rg");
                if let Ty::Result_(ok, _) = &args[0].ty {
                    let ok_z = zig_ty(ok);
                    self.line(&format!("const {t}: {ok_z} = switch ({a}) {{"));
                    self.indent += 1;
                    if boxed_in_payload(ok) {
                        self.line(".Ok => |p| p.*,");
                    } else {
                        self.line(".Ok => |x| x,");
                    }
                    self.line(&format!(".Err => {d},"));
                    self.indent -= 1;
                    self.line("};");
                    t
                } else {
                    unreachable_shape("ResGetOr non-result")
                }
            }
            // Mutating list builtins appear as MutBuiltin when they mutate;
            // ListAppend as expression-method may still show as Builtin in
            // some lowerings — handle both.
            Builtin::ListAppend
            | Builtin::ListPop
            | Builtin::ListInsert
            | Builtin::ListRemoveAt
            | Builtin::ListSwap
            | Builtin::ListSort => unreachable_shape(&format!(
                "builtin {b:?} as non-mutating (expected MutBuiltin)"
            )),
            Builtin::NewMap | Builtin::NewSet => {
                let t = self.tmp("coll");
                let ty = zig_ty(result_ty);
                let a = self.cur_alloc();
                self.line(&format!("var {t}: {ty} = .{{ .alloc = {a} }};"));
                self.line(&format!("_ = &{t};"));
                t
            }
            Builtin::MapSize | Builtin::SetSize => {
                let a = self.expr(&args[0]);
                format!("{a}.size()")
            }
            Builtin::MapHas => {
                let m = self.expr(&args[0]);
                let k = self.expr(&args[1]);
                format!("{m}.has({k})")
            }
            Builtin::SetHas => {
                let s = self.expr(&args[0]);
                let v = self.expr(&args[1]);
                format!("{s}.has({v})")
            }
            Builtin::MapGet => {
                // Map.get(k) → Option<V>: deep-copy the value; box composite payload.
                let m = self.expr(&args[0]);
                let k = self.expr(&args[1]);
                let inner = match result_ty {
                    Ty::Option_(v) => v.as_ref(),
                    _ => unreachable!("MapGet result is Option"),
                };
                let copied = copy_expr(inner, "p.*", &self.cur_alloc());
                let payload = if boxed_in_payload(inner) {
                    format!("rt.box({}, {}, {copied})", self.cur_alloc(), zig_ty(inner))
                } else {
                    copied
                };
                let t = self.tmp("get");
                let ty = zig_ty(result_ty);
                self.line(&format!(
                    "const {t}: {ty} = if ({m}.getPtr({k})) |p| {payload} else null;"
                ));
                t
            }
            Builtin::MapKeys => {
                let key_ty = match &args[0].ty {
                    Ty::Map(k, _) => k.as_ref().clone(),
                    _ => unreachable!("MapKeys on non-map"),
                };
                self.emit_collect_list(&args[0], result_ty, "kv.k", &key_ty)
            }
            Builtin::MapValues => {
                let val_ty = match &args[0].ty {
                    Ty::Map(_, v) => v.as_ref().clone(),
                    _ => unreachable!("MapValues on non-map"),
                };
                self.emit_collect_list(&args[0], result_ty, "kv.v", &val_ty)
            }
            Builtin::SetItems => {
                let elem_ty = match &args[0].ty {
                    Ty::Set(e) => e.as_ref().clone(),
                    _ => unreachable!("SetItems on non-set"),
                };
                self.emit_collect_list(&args[0], result_ty, "kv.*", &elem_ty)
            }
            Builtin::MapDelete
            | Builtin::SetAdd
            | Builtin::SetRemove => unreachable_shape(&format!(
                "builtin {b:?} as non-mutating (expected MutBuiltin)"
            )),
        }
    }

    /// Build a `List<E>` by iterating a Map/Set snapshot, copying each element.
    /// `elem_expr` is `kv.k` / `kv.v` (map) or `kv.*` (set value iterator).
    fn emit_collect_list(
        &mut self,
        coll: &IrExpr,
        result_ty: &Ty,
        elem_expr: &str,
        elem_ty: &Ty,
    ) -> String {
        let c = self.expr(coll);
        let snap = self.tmp("snap");
        let snap_ty = zig_ty(&coll.ty);
        self.line(&format!("var {snap}: {snap_ty} = {c};"));
        self.line(&format!("_ = &{snap};"));
        let out = self.tmp("out");
        let out_ty = zig_ty(result_ty);
        let a = self.cur_alloc();
        self.line(&format!("var {out}: {out_ty} = .{{ .alloc = {a} }};"));
        self.line(&format!("_ = &{out};"));
        let it = self.tmp("it");
        self.line(&format!("var {it} = {snap}.map.valueIterator();"));
        self.line(&format!("while ({it}.next()) |kv| {{"));
        self.indent += 1;
        let copied = copy_expr(elem_ty, elem_expr, &a);
        self.line(&format!("{out}.append({copied}) catch @panic(\"sudo: arena OOM\");"));
        self.indent -= 1;
        self.line("}");
        out
    }

    /// Lvalue for a `MutBuiltin` receiver. Unlike `place_lvalue` (bare
    /// locals / fields-of-locals only), this also handles receivers reached
    /// through a list/map index (`xs[0].append(v)`, `m[k].append(v)`,
    /// `p.field[i].append(v)`) by borrowing the element in place via
    /// `atPtr`/`getPtr` and calling the mutating method through the
    /// resulting pointer (Zig auto-derefs pointer receivers for method
    /// calls, so callers can use this exactly like `place_lvalue`'s result).
    fn mut_recv_lvalue(&mut self, p: &Place) -> String {
        if let Place::Index { base, base_ty, index } = p {
            let base_lv = self.place_lvalue(base);
            let idx = self.expr(index);
            return match base_ty {
                Ty::List(_) => self.tryx(&format!("{base_lv}.atPtr({idx})")),
                Ty::Map(..) => {
                    let raise = self.raise("rt.SudoError.KeyMissing");
                    format!("({base_lv}.getPtr({idx}) orelse {raise})")
                }
                other => unreachable_shape(&format!("mut recv Index on {other:?}")),
            };
        }
        self.place_lvalue(p)
    }

    fn emit_mut_builtin(
        &mut self,
        b: Builtin,
        recv: &Place,
        recv_ty: &Ty,
        args: &[IrExpr],
        result_ty: &Ty,
    ) -> String {
        // Method-style mutators take an lvalue receiver (Zig auto-refs);
        // only the free-function sort helpers need a real `*T` pointer.
        let recv_lv = self.mut_recv_lvalue(recv);
        let _ = result_ty;
        match b {
            Builtin::ListAppend => {
                let esc = self.place_escapes(recv);
                let v = self.store_to(&args[0], &format!("{recv_lv}.alloc"), esc);
                self.try_line(&format!("{recv_lv}.append({v})"));
                // Void result for expression context (`_ = {}`).
                "{}".into()
            }
            Builtin::ListPop => {
                self.tryx(&format!("{recv_lv}.pop()"))
            }
            Builtin::ListInsert => {
                let idx = self.expr(&args[0]);
                let esc = self.place_escapes(recv);
                let v = self.store_to(&args[1], &format!("{recv_lv}.alloc"), esc);
                self.try_line(&format!("{recv_lv}.insert({idx}, {v})"));
                "{}".into()
            }
            Builtin::ListRemoveAt => {
                let idx = self.expr(&args[0]);
                self.tryx(&format!("{recv_lv}.removeAt({idx})"))
            }
            Builtin::ListSwap => {
                let i = self.expr(&args[0]);
                let j = self.expr(&args[1]);
                self.try_line(&format!("{recv_lv}.swap({i}, {j})"));
                "{}".into()
            }
            Builtin::ListSort => {
                let ptr = self.place_ptr(recv);
                match recv_ty {
                    Ty::List(elem) if matches!(elem.as_ref(), Ty::Int) => {
                        self.line(&format!("rt.sortI64({ptr});"));
                    }
                    Ty::List(elem) if matches!(elem.as_ref(), Ty::Float) => {
                        self.line(&format!("rt.sortF64({ptr});"));
                    }
                    _ => unreachable_shape("ListSort non int/float"),
                }
                "{}".into()
            }
            Builtin::MapDelete => {
                let k = self.store(&args[0]);
                format!("{recv_lv}.delete({k})")
            }
            Builtin::SetAdd => {
                // The set RETAINS the element value, so it must outlive the
                // loop arena — copy it into the set's own allocator.
                let esc = self.place_escapes(recv);
                let v = self.store_to(&args[0], &format!("{recv_lv}.alloc"), esc);
                format!("{recv_lv}.add({v})")
            }
            Builtin::SetRemove => {
                let v = self.expr(&args[0]);
                format!("{recv_lv}.remove({v})")
            }
            other => unreachable_shape(&format!("mut builtin {other:?}")),
        }
    }

    fn tmp(&mut self, tag: &str) -> String {
        let n = self.tmp;
        self.tmp += 1;
        format!("_sudo_{tag}{n}")
    }

    /// A fallible call as an expression. Normally `(try X)`; inside an
    /// `expect_trap` block, `(X catch |e| break :label e)` so the trap is
    /// observed locally rather than propagating out of the test function.
    /// Zig labeled blocks are ordinary scopes (not namespace boundaries), so
    /// the body still sees enclosing locals — no capture, unlike a nested fn.
    fn tryx(&self, inner: &str) -> String {
        match &self.trap_label {
            Some(l) => format!("({inner} catch |_sudo_e| break :{l} _sudo_e)"),
            None => format!("(try {inner})"),
        }
    }

    /// Emit a fallible statement `try X;` (or the `catch break` form).
    fn try_line(&mut self, inner: &str) {
        let s = self.tryx(inner);
        self.line(&format!("{s};"));
    }

    /// The allocator expression used at every codegen allocation/creation site
    /// (container literals, `rt.box`, top-level `copy_*` calls). Inside a loop
    /// body this is the per-loop arena; inside a sudo function body (outside
    /// loops) the per-call scratch arena; outside, an override (per-test `ta` /
    /// const-init `ca`) if set; else a fallback string that is statically
    /// unreachable after Stage 3.
    fn cur_alloc(&mut self) -> String {
        if self.loop_depth > 0 {
            if let Some(a) = &self.loop_arena {
                return a.clone();
            }
        }
        if self.in_func_body {
            self.scratch_used = true;
            return "_sudo_scratch.allocator()".to_string();
        }
        if let Some(a) = &self.alloc_override {
            return a.clone();
        }
        "rt.allocator()".to_string() // fallback; should be unreachable after Stage 3
    }

    /// Force allocation of an escape-copy into the ENCLOSING (non-loop)
    /// allocator — function scratch inside bodies, test/const override outside.
    /// Loop-carried values must land here so they survive the per-iteration reset.
    fn scratch_alloc(&mut self) -> String {
        if self.in_func_body {
            self.scratch_used = true;
            return "_sudo_scratch.allocator()".to_string();
        }
        if let Some(a) = &self.alloc_override {
            return a.clone();
        }
        "rt.allocator()".to_string()
    }

    /// Enter a loop. If this is the OUTERMOST loop in the function *and* the
    /// body can allocate, create a per-loop arena at the current indent and
    /// return its VAR name (so the caller emits the per-iteration reset).
    /// Pure-scalar loops skip the arena (callers fall back to plain `while`).
    /// Nested loops reuse the outer arena (return None). Always bumps
    /// `loop_depth` so `escapes_loop` keeps working regardless of arena.
    fn enter_loop(&mut self, body: &[IrStmt]) -> Option<String> {
        let created = if self.loop_depth == 0 && loop_body_allocates(body, self.m, self.all)
        {
            let a = self.tmp("loop");
            self.line(&format!("var {a} = rt.ArenaAllocator.init(rt.backing());"));
            self.line(&format!("defer {a}.deinit();"));
            self.loop_arena = Some(format!("{a}.allocator()"));
            Some(a)
        } else {
            // Nested, or outermost pure-scalar: no (new) arena. Leave
            // `loop_arena` as-is (None at depth 0; outer's at depth > 0).
            None
        };
        self.loop_depth += 1;
        created
    }

    fn exit_loop(&mut self) {
        self.loop_depth -= 1;
        if self.loop_depth == 0 {
            self.loop_arena = None;
            self.loop_declared.clear();
        }
    }

    /// True when `root` is a local that lives OUTSIDE the current outermost
    /// loop (function scope) while we are inside that loop — i.e. assigning to
    /// it or storing into it crosses the iteration boundary and must escape
    /// to scratch.
    fn escapes_loop(&self, root: &str) -> bool {
        self.loop_depth > 0 && !self.loop_declared.contains(root)
    }

    /// Record a local declared in the current scope (tracks loop membership).
    fn note_declared(&mut self, name: &str) {
        if self.loop_depth > 0 {
            self.loop_declared.insert(name.to_string());
        }
    }

    /// Whether the root local of `p` is an inout param or a loop-carried local
    /// (container/value may outlive this iteration's loop arena / scratch).
    fn place_escapes(&self, p: &Place) -> bool {
        match place_root_local(p) {
            Some(n) => self.inouts.contains(n) || self.escapes_loop(n),
            None => false,
        }
    }

    /// Raise a trap: `return ERR` normally; `break :label ERR` in expect_trap.
    fn raise(&self, err: &str) -> String {
        match &self.trap_label {
            Some(l) => format!("break :{l} {err}"),
            None => format!("return {err}"),
        }
    }

    fn line(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn blank(&mut self) {
        self.out.push('\n');
    }
}

// ── helpers ─────────────────────────────────────────────────────────────────

fn unreachable_shape(what: &str) -> ! {
    panic!("internal error: unreachable emission shape: {what} (guarded upstream by the checker)");
}

fn is_scalar(ty: &Ty) -> bool {
    matches!(ty, Ty::Int | Ty::Float | Ty::Bool)
}

/// Payload field of enum/Option/Result: box Record/Enum/Option/Result/Tuple.
fn boxed_in_payload(ty: &Ty) -> bool {
    matches!(
        ty,
        Ty::Record(_) | Ty::Enum(_) | Ty::Option_(_) | Ty::Result_(..) | Ty::Tuple(_)
    )
}

fn payload_ty(ty: &Ty) -> String {
    if boxed_in_payload(ty) {
        format!("*const {}", zig_ty(ty))
    } else {
        zig_ty(ty)
    }
}

fn mangle(ty: &Ty) -> String {
    sudoc_ir::mangle::mangle_ty(ty)
}

/// True when `ty` contains no module-local `Record`/`Enum` anywhere in its
/// shape — safe to declare once in `sudo_types.zig` and share across modules.
fn is_portable(ty: &Ty) -> bool {
    match ty {
        Ty::Int | Ty::Float | Ty::Bool => true,
        Ty::Record(_) | Ty::Enum(_) => false,
        Ty::List(e) | Ty::Set(e) | Ty::Option_(e) => is_portable(e),
        Ty::Map(k, v) => is_portable(k) && is_portable(v),
        Ty::Result_(a, b) => is_portable(a) && is_portable(b),
        Ty::Tuple(ts) => ts.iter().all(is_portable),
        Ty::Func { params, ret } => {
            params.iter().all(is_portable)
                && ret.as_ref().map(|r| is_portable(r)).unwrap_or(true)
        }
        Ty::Infer(_) => unreachable!("Infer escaped the checker"),
    }
}

fn zig_ty(ty: &Ty) -> String {
    match ty {
        Ty::Int => "i64".into(),
        Ty::Float => "f64".into(),
        Ty::Bool => "bool".into(),
        Ty::List(_)
        | Ty::Tuple(_)
        | Ty::Option_(_)
        | Ty::Result_(..)
        | Ty::Record(_)
        | Ty::Enum(_)
        | Ty::Map(..)
        | Ty::Set(_) => mangle(ty),
        Ty::Func { params, ret } => {
            // `rt.Allocator` (= std.mem.Allocator); modules only import `rt`, not `std`.
            let mut ps: Vec<String> = vec!["rt.Allocator".into()];
            ps.extend(params.iter().map(zig_ty));
            let r = match ret {
                Some(r) => zig_ty(r),
                None => "void".into(),
            };
            format!("*const fn ({}) rt.SudoError!{r}", ps.join(", "))
        }
        Ty::Infer(_) => unreachable!("Infer escaped the checker"),
    }
}

/// Base local name of a place chain (`xs` for `xs`, `xs.f`, `xs[i]`, …).
fn place_root_local(p: &Place) -> Option<&str> {
    match p {
        Place::Var(n) => Some(n.as_str()),
        Place::Field { base, .. } | Place::Index { base, .. } => place_root_local(base),
    }
}

fn is_container_ty(ty: &Ty) -> bool {
    matches!(ty, Ty::List(_) | Ty::Map(..) | Ty::Set(_))
}

fn needs_dup(ty: &Ty) -> bool {
    match ty {
        Ty::List(_) | Ty::Map(..) | Ty::Set(_) | Ty::Record(_) | Ty::Enum(_) => true,
        Ty::Tuple(ts) => ts.iter().any(needs_dup),
        Ty::Option_(t) => needs_dup(t) || boxed_in_payload(t),
        Ty::Result_(a, b) => {
            needs_dup(a) || needs_dup(b) || boxed_in_payload(a) || boxed_in_payload(b)
        }
        _ => false,
    }
}

fn aliasing(kind: &IrExprKind) -> bool {
    match kind {
        IrExprKind::Local(_)
        | IrExprKind::Const(_)
        | IrExprKind::GetField { .. }
        | IrExprKind::Index { .. } => true,
        IrExprKind::Builtin { builtin, .. } => matches!(
            builtin,
            Builtin::OptUnwrap | Builtin::OptGetOr | Builtin::ResUnwrap | Builtin::ResGetOr
        ),
        _ => false,
    }
}

fn eq_expr(ty: &Ty, a: &str, b: &str) -> String {
    if is_scalar(ty) || matches!(ty, Ty::Func { .. }) {
        format!("({a} == {b})")
    } else {
        format!("eq_{}({a}, {b})", mangle(ty))
    }
}

/// Deep-copy `e` if the type owns heap; otherwise pass through. `alloc` is the
/// allocator expression threaded into the `copy_*` call (the enclosing
/// `copy_*`'s own `alloc` param inside `emit_type_ops`, else `cur_alloc()`).
fn copy_expr(ty: &Ty, e: &str, alloc: &str) -> String {
    if needs_dup(ty) {
        format!("copy_{}({alloc}, {e})", mangle(ty))
    } else {
        e.to_string()
    }
}

/// The `appendKey` function passed to `rt.SudoMap`/`rt.SudoSet` for key type `ty`.
fn keyapp_fn(ty: &Ty) -> String {
    match ty {
        Ty::Int => "rt.key_i64".into(),
        Ty::Bool => "rt.key_bool".into(),
        Ty::Float => unreachable_shape("float map/set key"),
        _ => format!("keyapp_{}", mangle(ty)),
    }
}

/// Composite types that need a `keyapp_*` encoder: every Map/Set key type and
/// its composite sub-parts (scalars route directly to `rt.key_i64/key_bool`).
fn collect_key_types(types: &TypeSet, m: &IrModule) -> Vec<String> {
    fn add_composite(ty: &Ty, m: &IrModule, out: &mut BTreeSet<String>) {
        match ty {
            Ty::Int | Ty::Bool | Ty::Float => {}
            Ty::List(e) | Ty::Option_(e) => {
                out.insert(mangle(ty));
                add_composite(e, m, out);
            }
            Ty::Tuple(ts) => {
                out.insert(mangle(ty));
                for t in ts {
                    add_composite(t, m, out);
                }
            }
            Ty::Result_(a, b) => {
                out.insert(mangle(ty));
                add_composite(a, m, out);
                add_composite(b, m, out);
            }
            Ty::Record(n) if out.insert(mangle(ty)) => {
                if let Some(r) = m.record(n) {
                    for f in &r.fields {
            let t = &f.ty;
                        add_composite(t, m, out);
                    }
                }
            }
            Ty::Enum(n) if out.insert(mangle(ty)) => {
                if let Some(e) = m.enum_(n) {
                    for v in &e.variants {
                        for f in &v.fields {
            let t = &f.ty;
                            add_composite(t, m, out);
                        }
                    }
                }
            }
            // Map/Set/Func are never key-eligible (the checker guarantees it).
            _ => {}
        }
    }
    let mut out = BTreeSet::new();
    for ty in types.types.values() {
        match ty {
            Ty::Map(k, _) => add_composite(k, m, &mut out),
            Ty::Set(e) => add_composite(e, m, &mut out),
            _ => {}
        }
    }
    out.into_iter().collect()
}

fn qualify_name(name: &str) -> String {
    name.to_string()
}

