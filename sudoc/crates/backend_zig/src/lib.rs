/// Like resolve by bare/`module.func` name, but also returns the module that
/// owns the function (needed so borrow eligibility runs against the callee's
/// own module, not the caller's).
fn resolve_func_and_module_in<'a>(
    m: &'a IrModule,
    all: &'a [IrModule],
    name: &str,
) -> Option<(&'a IrModule, &'a IrFunc)> {
    match name.split_once('.') {
        Some((modname, fname)) => {
            let mm = all.iter().find(|mm| mm.name == modname)?;
            Some((mm, mm.func(fname)?))
        }
        None => Some((m, m.func(name)?)),
    }
}

/// Param names of `f` that may be emitted as `*const T` borrows: managed type,
/// never written by the body, not `inout`, and `f` is never taken as a value.
fn func_borrow_eligible(
    f: &IrFunc,
    owning: &IrModule,
    address_taken: &HashSet<String>,
) -> HashSet<String> {
    if func_is_address_taken(owning, f, address_taken) {
        return HashSet::new();
    }
    f.params
        .iter()
        .filter(|p| !p.inout && needs_dup(&p.ty) && p.never_written)
        .map(|p| p.name.clone())
        .collect()
}

/// Field-access chain rooted in a `Local` (no Index / call / etc.).
fn is_simple_place(e: &IrExpr) -> bool {
    match &e.kind {
        IrExprKind::Local(_) => true,
        IrExprKind::GetField { recv, .. } => is_simple_place(recv),
        _ => false,
    }
}

fn simple_place(e: &IrExpr) -> Place {
    match &e.kind {
        IrExprKind::Local(n) => Place::Var(n.clone()),
        IrExprKind::GetField { recv, name } => Place::Field {
            base: Box::new(simple_place(recv)),
            base_ty: recv.ty.clone(),
            name: name.clone(),
        },
        _ => unreachable!("is_simple_place guards this"),
    }
}

/// Whether `name` is referenced anywhere in `stmts` (match-arm body). Used
/// to emit `_ = binder;` for deliberately unused variant binders so Zig
/// does not reject them as unused local constants.
fn binder_used(stmts: &[IrStmt], name: &str) -> bool {
    fn expr_uses(e: &IrExpr, name: &str) -> bool {
        match &e.kind {
            IrExprKind::Local(n) => n == name,
            IrExprKind::List(xs)
            | IrExprKind::Tuple(xs)
            | IrExprKind::CallFunc { args: xs, .. }
            | IrExprKind::NewRecord { args: xs, .. }
            | IrExprKind::NewVariant { args: xs, .. }
            | IrExprKind::Builtin { args: xs, .. } => xs.iter().any(|x| expr_uses(x, name)),
            IrExprKind::CallValue { callee, args } => {
                expr_uses(callee, name) || args.iter().any(|x| expr_uses(x, name))
            }
            IrExprKind::MutBuiltin { recv, args, .. } => {
                place_uses(recv, name) || args.iter().any(|x| expr_uses(x, name))
            }
            IrExprKind::GetField { recv, .. } => expr_uses(recv, name),
            IrExprKind::Index { recv, index } => {
                expr_uses(recv, name) || expr_uses(index, name)
            }
            IrExprKind::Unary { operand, .. } => expr_uses(operand, name),
            IrExprKind::Binary { lhs, rhs, .. } => {
                expr_uses(lhs, name) || expr_uses(rhs, name)
            }
            _ => false,
        }
    }
    fn place_uses(p: &Place, name: &str) -> bool {
        match p {
            Place::Var(n) => n == name,
            Place::Index { base, index, .. } => {
                place_uses(base, name) || expr_uses(index, name)
            }
            Place::Field { base, .. } => place_uses(base, name),
        }
    }
    stmts.iter().any(|s| match s {
        IrStmt::Assign { target, value, .. } => {
            place_uses(target, name) || expr_uses(value, name)
        }
        IrStmt::TupleAssign { targets, value, .. } => {
            targets.iter().any(|t| t == name) || expr_uses(value, name)
        }
        IrStmt::Expr(e) => expr_uses(e, name),
        IrStmt::If { arms, else_block } => {
            arms.iter().any(|(c, b)| expr_uses(c, name) || binder_used(b, name))
                || else_block.as_ref().is_some_and(|b| binder_used(b, name))
        }
        IrStmt::While { cond, body } => expr_uses(cond, name) || binder_used(body, name),
        IrStmt::ForRange { from, to, body, .. } => {
            expr_uses(from, name) || expr_uses(to, name) || binder_used(body, name)
        }
        IrStmt::ForIn { iter, body, .. } => expr_uses(iter, name) || binder_used(body, name),
        IrStmt::Match { scrutinee, arms } => {
            expr_uses(scrutinee, name) || arms.iter().any(|a| binder_used(&a.body, name))
        }
        IrStmt::Return(Some(e)) => expr_uses(e, name),
        IrStmt::Assert { cond, .. } => expr_uses(cond, name),
        IrStmt::ExpectTrap { body, .. } => binder_used(body, name),
        IrStmt::Return(None) | IrStmt::Skip | IrStmt::Break | IrStmt::Continue => false,
    })
}

/// True if `body` may allocate into `cur_alloc()` (so the outermost loop needs
/// a per-iteration arena). Over-approximates: a false positive only adds an
/// unused arena; a false negative falls back to function scratch (correct but
/// no per-iteration reclaim). Walks nested If/Match arms, nested loops, and
/// ExpectTrap bodies — same shape as `collect_written` / `written_expr`.
///
/// `m`/`all` are currently unused: calls are treated as allocating without
/// resolving callees (safe over-approx). Kept for parity with the other IR
/// walkers and future refinements.
fn loop_body_allocates(body: &[IrStmt], _m: &IrModule, _all: &[IrModule]) -> bool {
    stmts_allocate(body)
}

fn stmts_allocate(body: &[IrStmt]) -> bool {
    body.iter().any(stmt_allocates)
}

fn stmt_allocates(s: &IrStmt) -> bool {
    match s {
        IrStmt::Assign { target, value, .. } => {
            // Index assign mutates a container (put may retain/copy into it).
            if matches!(target, Place::Index { .. }) {
                return true;
            }
            // Storing a composite deep-copies into cur_alloc / escape dest.
            if needs_dup(&value.ty) {
                return true;
            }
            expr_allocates(value)
        }
        IrStmt::TupleAssign { value, .. } => {
            needs_dup(&value.ty) || expr_allocates(value)
        }
        IrStmt::Expr(e) => expr_allocates(e),
        IrStmt::If { arms, else_block } => {
            arms.iter()
                .any(|(c, b)| expr_allocates(c) || stmts_allocate(b))
                || else_block.as_ref().is_some_and(|b| stmts_allocate(b))
        }
        IrStmt::While { cond, body } => expr_allocates(cond) || stmts_allocate(body),
        IrStmt::ForRange {
            from, to, body, ..
        } => expr_allocates(from) || expr_allocates(to) || stmts_allocate(body),
        IrStmt::ForIn { iter, body, .. } => expr_allocates(iter) || stmts_allocate(body),
        IrStmt::Match { scrutinee, arms } => {
            expr_allocates(scrutinee) || arms.iter().any(|a| stmts_allocate(&a.body))
        }
        IrStmt::Return(Some(e)) => needs_dup(&e.ty) || expr_allocates(e),
        IrStmt::Assert { cond, .. } => expr_allocates(cond),
        IrStmt::ExpectTrap { body, .. } => stmts_allocate(body),
        IrStmt::Return(None) | IrStmt::Skip | IrStmt::Break | IrStmt::Continue => false,
    }
}

fn expr_allocates(e: &IrExpr) -> bool {
    match &e.kind {
        // Calls pass cur_alloc as the callee result allocator.
        IrExprKind::CallFunc { .. } | IrExprKind::CallValue { .. } => true,
        // Composite construction always (or may) allocate.
        IrExprKind::List(_) | IrExprKind::Text(_) => true,
        // Records/variants may box payloads or deep-copy field stores.
        IrExprKind::NewRecord { .. } | IrExprKind::NewVariant { .. } => true,
        IrExprKind::Tuple(xs) => {
            // Scalar tuples are stack-only; composite elems go through store().
            needs_dup(&e.ty) || xs.iter().any(expr_allocates)
        }
        IrExprKind::Builtin { builtin, args } => {
            builtin_allocates(*builtin) || args.iter().any(expr_allocates)
        }
        IrExprKind::MutBuiltin { builtin, args, .. } => {
            // Container mutations (append/insert/add/delete) may grow/retain.
            mut_builtin_allocates(*builtin) || args.iter().any(expr_allocates)
        }
        IrExprKind::GetField { recv, .. } => expr_allocates(recv),
        IrExprKind::Index { recv, index } => {
            // Index itself does not allocate; sub-exprs might.
            expr_allocates(recv) || expr_allocates(index)
        }
        IrExprKind::Unary { operand, .. } => expr_allocates(operand),
        IrExprKind::Binary { op, lhs, rhs, .. } => {
            // List concat builds a fresh list in cur_alloc.
            (matches!(op, BinaryOp::Add) && matches!(e.ty, Ty::List(_)))
                || expr_allocates(lhs)
                || expr_allocates(rhs)
        }
        IrExprKind::Int(_)
        | IrExprKind::Float(_)
        | IrExprKind::Bool(_)
        | IrExprKind::Local(_)
        | IrExprKind::Const(_)
        | IrExprKind::FuncRef(_) => false,
    }
}

/// Builtins that construct a container or copy into cur_alloc.
fn builtin_allocates(b: Builtin) -> bool {
    matches!(
        b,
        Builtin::Filled
            | Builtin::NewMap
            | Builtin::NewSet
            | Builtin::MapKeys
            | Builtin::MapValues
            | Builtin::SetItems
            // MapGet deep-copies (and may box) the value into cur_alloc.
            | Builtin::MapGet
            // Defaults may be composite stores into cur_alloc.
            | Builtin::OptGetOr
            | Builtin::ResGetOr
    )
}

/// Mutating builtins that may allocate / retain into the receiver's storage
/// (or otherwise need a live loop arena for transient args).
fn mut_builtin_allocates(b: Builtin) -> bool {
    matches!(
        b,
        Builtin::ListAppend
            | Builtin::ListInsert
            | Builtin::SetAdd
            | Builtin::MapDelete
            // Over-approximate remaining mutators (safe: unused arena only).
            | Builtin::ListPop
            | Builtin::ListRemoveAt
            | Builtin::ListSwap
            | Builtin::ListSort
            | Builtin::SetRemove
    )
}

fn expr_as_place(e: &IrExpr) -> Place {
    match &e.kind {
        IrExprKind::Local(n) => Place::Var(n.clone()),
        IrExprKind::GetField { recv, name } => Place::Field {
            base: Box::new(expr_as_place(recv)),
            base_ty: recv.ty.clone(),
            name: name.clone(),
        },
        other => unreachable!("inout arg is not a place: {other:?}"),
    }
}

fn can_trap(e: &IrExpr) -> bool {
    match &e.kind {
        IrExprKind::Int(_)
        | IrExprKind::Float(_)
        | IrExprKind::Bool(_)
        | IrExprKind::Local(_)
        | IrExprKind::Const(_)
        | IrExprKind::FuncRef(_)
        | IrExprKind::Text(_) => false,
        IrExprKind::CallFunc { .. } | IrExprKind::CallValue { .. } => true,
        IrExprKind::Unary { op, operand } => {
            (matches!(op, UnaryOp::Neg) && matches!(operand.ty, Ty::Int)) || can_trap(operand)
        }
        IrExprKind::Binary { op, lhs, rhs } => {
            let arith_trap = matches!(lhs.ty, Ty::Int)
                && matches!(
                    op,
                    BinaryOp::Add
                        | BinaryOp::Sub
                        | BinaryOp::Mul
                        | BinaryOp::Div
                        | BinaryOp::Mod
                );
            arith_trap || can_trap(lhs) || can_trap(rhs)
        }
        IrExprKind::Builtin { builtin, args } => {
            let traps = matches!(
                builtin,
                Builtin::AbsInt
                    | Builtin::IntOfFloat
                    | Builtin::OptUnwrap
                    | Builtin::ResUnwrap
                    | Builtin::ListPop
                    | Builtin::ListRemoveAt
            );
            traps || args.iter().any(can_trap)
        }
        IrExprKind::List(xs) | IrExprKind::Tuple(xs) => xs.iter().any(can_trap),
        IrExprKind::NewRecord { args, .. } | IrExprKind::NewVariant { args, .. } => {
            args.iter().any(can_trap)
        }
        IrExprKind::GetField { recv, .. } => can_trap(recv),
        IrExprKind::Index { .. } | IrExprKind::MutBuiltin { .. } => true,
    }
}

